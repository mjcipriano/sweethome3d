  String getId(Object item) {
    String id = HomeItemIds.getId(item);
    if (id == null && item instanceof HomeObject) {
      // An item added during the turn
      HomeItemIds.ensureIds(this.home);
      id = HomeItemIds.getId(item);
    }
    return id;
  }

