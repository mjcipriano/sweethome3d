  /**
   * Runs at most <code>maxCommandCount</code> commands as a single undoable change:
   * a file of commands may hold more of them than a reply typed by a model.
   */
  public String execute(List<AssistantCommand> commands, int maxCommandCount) {
    if (commands == null || commands.isEmpty()) {
      return null;
    }
    this.groupActivityTime = System.currentTimeMillis();
    // furniture, doors/windows, rooms, walls, modified items, deleted items
    int [] tally = new int [6];
    List<String> notFound = new ArrayList<String>();
    List<String> notes = new ArrayList<String>();
    // Ids (F#/W#/R#) designate the items the model saw at the start of the turn,
    // whatever earlier commands of the same turn added or deleted
    HomeItemIds.ensureIds(this.home);
    this.turnFurniture = new ArrayList<HomePieceOfFurniture>(this.home.getFurniture());
    this.turnWalls = new ArrayList<Wall>(this.home.getWalls());
    this.turnRooms = new ArrayList<Room>(this.home.getRooms());
    List<Polyline> polylinesBefore = new ArrayList<Polyline>(this.home.getPolylines());
    List<Level> levelsBefore = new ArrayList<Level>(this.home.getLevels());
    List<HomePieceOfFurniture> furnitureBefore = this.turnFurniture;
    List<Wall> wallsBefore = this.turnWalls;
    List<Room> roomsBefore = this.turnRooms;
    this.turnUpdateBegun = false;
    this.turnUnresolvedIds = new ArrayList<String>();
    this.turnWarnings = new ArrayList<String>();
    try {
      int applied = 0;
      List<String> results = new ArrayList<String>();
      boolean anyIssue = false;
      Object lastCreated = null;
      for (AssistantCommand command : commands) {
        if (++applied > maxCommandCount) {
          notes.add("Stopped after " + maxCommandCount
              + " commands (turn limit); " + (commands.size() - maxCommandCount)
              + " commands were ignored");
          break;
        }
        int noteCount = notes.size();
        int notFoundCount = notFound.size();
        int warningCount = this.turnWarnings.size();
        int unresolvedCount = this.turnUnresolvedIds.size();
        int [] tallyBefore = tally.clone();
        int [] countsBefore = getItemCounts();
        replaceLastIds(command, lastCreated);
        try {
          applyCommand(command, tally, notFound, notes);
        } catch (RuntimeException ex) {
          // One failing command mustn't abort the turn or leave the compound edit open
          notes.add("Couldn't apply " + command.getAction() + " ("
              + (ex.getMessage() != null ? ex.getMessage() : ex.getClass().getSimpleName()) + ")");
        }
        Object created = getLastCreated(countsBefore);
        if (created != null) {
          lastCreated = created;
        }
        // What this command did, for the list of results
        boolean failed = notFound.size() > notFoundCount || this.turnUnresolvedIds.size() > unresolvedCount;
        for (int i = noteCount; i < notes.size(); i++) {
          String note = notes.get(i);
          if (note.startsWith("Couldn't ") || note.startsWith("Ignored ")) {
            failed = true;
            if (commands.size() > 1) {
              notes.set(i, "Command " + applied + ": " + note);
            }
          }
        }
        boolean changed = !java.util.Arrays.equals(tallyBefore, tally) || notes.size() > noteCount
            || this.turnWarnings.size() > warningCount;
        // A command that edits and changed nothing is told, rather than taken for done
        boolean editing = java.util.Arrays.asList("move", "rotate", "resize", "set_color", "set_elevation", "set_visible", "rename",
            "delete", "remove", "modify_furniture", "add_furniture", "add_door_or_window", "add_room", "add_wall").contains(command.getAction());
        String result = failed ? command.getAction() + " failed" : changed || !editing ? "ok" : command.getAction() + " did nothing";
        anyIssue |= !result.equals("ok");
        results.add(result);
        if (failed && this.stopOnError) {
          if (applied < commands.size()) {
            notes.add("Stopped at the command " + applied + ", which failed (stop_on_error): the "
                + (commands.size() - applied) + " commands after it weren't run");
          }
          break;
        }
      }
      if (commands.size() > 1 && anyIssue) {
        // The commands that worked, as ranges
        StringBuilder text = new StringBuilder("Results by command: ");
        int index = 0;
        while (index < results.size()) {
          int last = index;
          while (results.get(index).equals("ok") && last + 1 < results.size() && results.get(last + 1).equals("ok")) {
            last++;
          }
          text.append(index > 0 ? ", " : "").append(index + 1).append(last > index ? "-" + (last + 1) : "").append(' ')
              .append(results.get(index));
          index = last + 1;
        }
        notes.add(text.toString());
      }
      if (!this.turnUnresolvedIds.isEmpty()) {
        // Said rather than skipped in silence, so a stale id isn't taken for a change
        String ids = this.turnUnresolvedIds.toString();
        notes.add("No item has the id " + ids.substring(1, ids.length() - 1)
            + " (deleted, or not in the last description of the home): nothing was done for "
            + (this.turnUnresolvedIds.size() == 1 ? "it" : "them")
            + ". Describe the home again to get the current ids");
      }
      notes.addAll(this.turnWarnings);
      // The items added by the turn get their ids now, in the order they were added
      HomeItemIds.ensureIds(this.home);
      // What commands create is told apart from what the user draws
      List<HomeObject> allItems = new ArrayList<HomeObject>();
      allItems.addAll(this.home.getFurniture());
      allItems.addAll(this.home.getWalls());
      allItems.addAll(this.home.getRooms());
      allItems.addAll(this.home.getPolylines());
      {
        for (HomeObject item : allItems) {
          if (item.getProperty(CREATED_BY_PROPERTY) == null
              && !(item instanceof HomePieceOfFurniture ? furnitureBefore.contains(item)
                  : item instanceof Wall ? wallsBefore.contains(item)
                  : item instanceof Room ? roomsBefore.contains(item) : polylinesBefore.contains(item))) {
            item.setProperty(CREATED_BY_PROPERTY, "agent");
          }
        }
      }
      String created = describeCreatedItems(furnitureBefore, wallsBefore, roomsBefore, polylinesBefore, levelsBefore);
      if (created != null) {
        notes.add(created);
      }
    } finally {
      if (this.turnUpdateBegun) {
        this.homeController.getUndoableEditSupport().endUpdate();
      }
      this.unresolvedIds = this.turnUnresolvedIds;
      this.turnUnresolvedIds = null;
      this.turnWarnings = null;
      this.turnFurniture = null;
      this.turnWalls = null;
      this.turnRooms = null;
      this.turnUpdateBegun = false;
    }
    return buildSummary(tally, notFound, notes);
  }

  /**
   * Returns the ids of the items the home has now and didn't have at the start of the turn.
   */
  private String describeCreatedItems(List<HomePieceOfFurniture> furnitureBefore, List<Wall> wallsBefore,
                                      List<Room> roomsBefore, List<Polyline> polylinesBefore, List<Level> levelsBefore) {
    List<HomeObject> created = new ArrayList<HomeObject>();
    Set<HomeObject> before = new HashSet<HomeObject>();
    before.addAll(levelsBefore);
    before.addAll(roomsBefore);
    before.addAll(wallsBefore);
    before.addAll(furnitureBefore);
    before.addAll(polylinesBefore);
    List<HomeObject> now = new ArrayList<HomeObject>();
    now.addAll(this.home.getLevels());
    now.addAll(this.home.getRooms());
    now.addAll(this.home.getWalls());
    now.addAll(this.home.getFurniture());
    now.addAll(this.home.getPolylines());
    for (HomeObject item : now) {
      if (!before.contains(item)) {
        created.add(item);
      }
    }
    if (created.isEmpty()) {
      return null;
    }
    StringBuilder text = new StringBuilder("Ids of what was created: ");
    int listed = 0;
    for (int i = 0; i < created.size(); i++) {
      HomeObject item = created.get(i);
      String id = HomeItemIds.getId(item);
      if (id == null) {
        continue;
      }
      if (listed == MAX_CREATED_IDS) {
        text.append(", and ").append(created.size() - i).append(" more (get_home lists them)");
        break;
      }
      text.append(listed++ > 0 ? ", " : "").append(id);
      String name = item instanceof HomePieceOfFurniture ? ((HomePieceOfFurniture)item).getName()
          : item instanceof Room ? ((Room)item).getName()
          : item instanceof Level ? ((Level)item).getName()
          : item instanceof Polyline ? item.getProperty(AssistantSiteCommands.LINE_NAME_PROPERTY) : null;
      if (name != null && name.length() > 0 && !(item instanceof Wall)) {
        text.append(" \"").append(name).append('"');
      }
    }
    return listed > 0 ? text.toString() : null;
  }

  /**
   * Returns one line for each of the items matching <code>where</code>, with the fields asked for:
   * <code>name</code>, <code>position</code>, <code>size</code>, <code>level</code>, <code>elevation</code>,
   * <code>angle</code>, <code>tags</code>, <code>type</code>, <code>area</code>, <code>points</code>,
   * <code>color</code>. The id of an item is always given.
   * @param where  the criteria of {@link #resolveWhere(Map)}, or <code>null</code> for every item
   * @param fields the fields to give, or <code>null</code> for the name, the position, the size and the level
   */
  public String describeItems(Map<?, ?> where, List<String> fields) {
    return describeItems(where, fields, 0, MAX_LISTED_ITEMS);
  }

  /**
   * Returns the same lines for <code>limit</code> items at most, from the one at the index <code>offset</code>.
   */
  public String describeItems(Map<?, ?> where, List<String> fields, int offset, int limit) {
    offset = Math.max(0, offset);
    limit = Math.max(1, Math.min(MAX_LISTED_ITEMS, limit));
    HomeItemIds.ensureIds(this.home);
    this.turnWarnings = new ArrayList<String>();
    List<Selectable> items;
    try {
      if (where != null && !where.isEmpty()) {
        items = resolveWhere(where);
      } else {
        items = new ArrayList<Selectable>();
        items.addAll(this.home.getRooms());
        items.addAll(this.home.getWalls());
        items.addAll(this.home.getFurniture());
        items.addAll(this.home.getPolylines());
      }
      if (!this.turnWarnings.isEmpty()) {
        return this.turnWarnings.get(0);
      }
    } finally {
      this.turnWarnings = null;
    }
    List<String> wanted = new ArrayList<String>();
    if (fields != null) {
      for (String field : fields) {
        wanted.add(field.trim().toLowerCase(Locale.ENGLISH));
      }
    }
    if (wanted.isEmpty()) {
      wanted.addAll(java.util.Arrays.asList("name", "position", "size", "level"));
    }
    StringBuilder text = new StringBuilder(items.size() + (items.size() == 1 ? " item" : " items")
        + (where != null && !where.isEmpty() ? " matching the filter" : "") + " (cm):\n");
    int listed = 0;
    if (offset > 0) {
      text.append("From the item ").append(offset + 1).append(":\n");
    }
    for (int itemIndex = offset; itemIndex < items.size(); itemIndex++) {
      Selectable item = items.get(itemIndex);
      if (listed++ == limit) {
        text.append("... and ").append(items.size() - offset - limit).append(" more: narrow the filter, or ask for the next ones with \"offset\":")
            .append(offset + limit).append('\n');
        break;
      }
      text.append("- ").append(getId(item));
      HomePieceOfFurniture piece = item instanceof HomePieceOfFurniture ? (HomePieceOfFurniture)item : null;
      Level level = item instanceof com.eteks.sweethome3d.model.Elevatable
          ? ((com.eteks.sweethome3d.model.Elevatable)item).getLevel() : null;
      for (String field : wanted) {
        if (field.equals("name")) {
          String name = piece != null ? piece.getName() : item instanceof Room ? ((Room)item).getName()
              : item instanceof Polyline ? ((Polyline)item).getProperty(AssistantSiteCommands.LINE_NAME_PROPERTY) : null;
          if (name != null) {
            text.append(" \"").append(name).append('"');
          }
        } else if (field.equals("position") || field.equals("x") || field.equals("y")) {
          if (piece != null) {
            text.append(" at (").append(Math.round(piece.getX())).append(", ").append(Math.round(piece.getY())).append(")");
          } else if (item instanceof Wall) {
            Wall wall = (Wall)item;
            text.append(" from (").append(Math.round(wall.getXStart())).append(", ").append(Math.round(wall.getYStart()))
                .append(") to (").append(Math.round(wall.getXEnd())).append(", ").append(Math.round(wall.getYEnd())).append(")");
          } else if (item instanceof Room) {
            text.append(" center (").append(Math.round(((Room)item).getXCenter())).append(", ")
                .append(Math.round(((Room)item).getYCenter())).append(")");
          }
        } else if (field.equals("size")) {
          if (piece != null) {
            text.append(' ').append(Math.round(piece.getWidth())).append(" x ").append(Math.round(piece.getDepth()))
                .append(" x ").append(Math.round(piece.getHeight()));
          } else if (item instanceof Wall) {
            text.append(' ').append(Math.round(((Wall)item).getLength())).append(" long");
          }
        } else if (field.equals("level")) {
          if (level != null) {
            text.append(" [").append(level.getName()).append(']');
          }
        } else if (field.equals("elevation") && piece != null) {
          text.append(" elevation ").append(Math.round(piece.getElevation()));
        } else if (field.equals("angle") && piece != null) {
          text.append(" angle ").append(Math.round(Math.toDegrees(piece.getAngle())));
        } else if (field.equals("tags") && piece != null && piece.getProperty(HomeItemTags.TAGS_PROPERTY) != null) {
          text.append(" tags ").append(piece.getProperty(HomeItemTags.TAGS_PROPERTY));
        } else if (field.equals("type")) {
          text.append(piece != null ? " " + HomeItemTags.getType(piece)
              : item instanceof Wall ? " wall" : item instanceof Room ? " room" : " line");
        } else if (field.equals("area") && item instanceof Room) {
          text.append(' ').append(Math.round(((Room)item).getArea() / 100) / 100f).append(" m2");
        } else if (field.equals("color") && piece != null && piece.getColor() != null) {
          text.append(String.format(" #%06X", piece.getColor() & 0xFFFFFF));
        } else if (field.equals("points") && (item instanceof Room || item instanceof Polyline)) {
          text.append(" points");
          for (float [] point : item.getPoints()) {
            text.append(" [").append(Math.round(point [0])).append(',').append(Math.round(point [1])).append(']');
          }
        }
      }
      text.append('\n');
    }
    return text.toString().trim();
  }

  // ---- Groups of calls undone as one step ----

  /**
   * Starts a group: the changes of the calls that follow, until {@link #endGroup()}, make one step
   * of Undo. Changes made by hand in the meantime join it.
   */
  public boolean beginGroup() {
    return beginGroup(null);
  }

  /**
   * Starts a group with a name, shown in the history of changes once the group is ended.
   */
  public boolean beginGroup(String name) {
    if (this.groupOpen) {
      return false;
    }
    this.groupName = name != null && name.trim().length() > 0 ? name.trim() : null;
    this.homeController.getUndoableEditSupport().beginUpdate();
    this.groupOpen = true;
    this.groupActivityTime = System.currentTimeMillis();
    return true;
  }

  /**
   * Ends the group started by {@link #beginGroup()}, and returns <code>false</code> if there is none.
   */
  public boolean endGroup() {
    if (!this.groupOpen) {
      return false;
    }
    this.groupOpen = false;
    final String name = this.groupName;
    this.groupName = null;
    if (name != null) {
      // The name of a group of edits is the one of its last edit
      this.homeController.getUndoableEditSupport().postEdit(new javax.swing.undo.AbstractUndoableEdit() {
          @Override
          public String getPresentationName() {
            return name;
          }
        });
    }
    this.homeController.getUndoableEditSupport().endUpdate();
    return true;
  }

  /**
   * Returns the name of the group that is open, or <code>null</code>.
   */
  public String getGroupName() {
    return this.groupOpen ? this.groupName : null;
  }

  public boolean isGroupOpen() {
    return this.groupOpen;
  }

  /**
   * Ends a group left open for longer than <code>delay</code> milliseconds without a command,
   * so a client that went away doesn't keep the changes of the user out of Undo.
   */
  public boolean endIdleGroup(long delay) {
    return this.groupOpen && System.currentTimeMillis() - this.groupActivityTime > delay && endGroup();
  }

  /**
   * Starts the compound undoable edit of the turn the first time a command
   * really changes the home, so a turn that changes nothing (a catalog search,
   * a selection, rejected commands) doesn't post an empty edit that would make
   * the home look modified and add a no-op Undo step.
   */
  void beginTurnUpdate() {
    if (!this.turnUpdateBegun) {
      this.homeController.getUndoableEditSupport().beginUpdate();
      this.turnUpdateBegun = true;
    }
  }

  private void applyCommand(AssistantCommand command, int [] tally, List<String> notFound,
                            List<String> notes) {
    String action = command.getAction();
    if ("search_catalog".equals(action) || "find_furniture".equals(action)) {
      searchCatalogCommand(command, notes);
    } else if ("help".equals(action)) {
      notes.add(AssistantHelp.getHelp(command.getString("command") != null ? command.getString("command") : command.getString("name"),
          command.getString("search"), command.getString("style")));
    } else if ("get_capabilities".equals(action)) {
      notes.add(AssistantHelp.getCapabilities());
    } else if ("add_furniture".equals(action)) {
      addFurniture(command, false, tally, notFound, notes);
    } else if ("add_door_or_window".equals(action) || "add_door".equals(action)
        || "add_window".equals(action)) {
      addFurniture(command, true, tally, notFound, notes);
    } else if ("add_room".equals(action)) {
      addRoom(command, tally, notes);
    } else if ("add_wall".equals(action)) {
      addWall(command, tally, notes);
    } else if ("select".equals(action)) {
      select(command, notes);
    } else if ("begin_group".equals(action) || "begin_undo_group".equals(action)) {
      notes.add(beginGroup(command.getString("name"))
          ? "Started a group" + (command.getString("name") != null ? " \"" + command.getString("name").trim() + "\"" : "") + ": what the calls change from now on is undone as one step, until {\"action\":\"end_group\"}. "
              + "It ends by itself after " + (GROUP_IDLE_DELAY / 60000) + " minutes without a command"
          : "A group is already started: {\"action\":\"end_group\"} ends it");
    } else if ("end_group".equals(action) || "end_undo_group".equals(action)) {
      notes.add(endGroup()
          ? "Ended the group: Edit > Undo now undoes at once everything changed since begin_group"
          : "No group was started");
    } else if ("modify_furniture".equals(action) || "modify_item".equals(action)) {
      modifyFurniture(command, tally, notFound, notes);
    } else if ("set_site_defaults".equals(action)) {
      if (command.has("on_terrain")) {
        boolean onTerrain = command.getBoolean("on_terrain", true);
        this.home.setProperty(OUTDOOR_ON_TERRAIN_PROPERTY, onTerrain ? null : "false");
        notes.add(onTerrain ? "Pieces added outdoors without elevation stand on the terrain"
            : "Pieces added outdoors without elevation stand at the elevation 0 of their level; \"on_terrain\":true puts one on the terrain");
      } else {
        notes.add("Couldn't run set_site_defaults (give \"on_terrain\":true or false)");
      }
    } else if ("optimize_models".equals(action)) {
      // The reduced model of the heavy pieces, the full one being kept for close views
      double minimum = Math.max(1, command.getDouble("min_kb", 500)) * 1024;
      List<String> ids = new ArrayList<String>();
      List<String> waiting = new ArrayList<String>();
      long weight = 0;
      for (HomePieceOfFurniture piece : this.home.getFurniture()) {
        if (piece.getModelSize() != null && piece.getModelSize() >= minimum && piece.isVisible()) {
          if (piece.getModel() != null && this.home.getModelLOD(piece.getModel()) != null) {
            if (!ModelLOD.isReducedDetailInView(piece)) {
              ids.add(getId(piece));
              weight += piece.getModelSize();
            }
          } else if (waiting.size() < 10) {
            waiting.add(getId(piece) + " \"" + piece.getName() + "\"");
          }
        }
      }
      if (!ids.isEmpty()) {
        Map<String, Object> parameters = new java.util.LinkedHashMap<String, Object>();
        parameters.put("ids", ids);
        applyCommand(new AssistantCommand("reduce_detail", parameters), tally, notFound, notes);
      }
      notes.add((ids.isEmpty() ? "No heavy model to reduce" : "Reduced the detail of " + ids.size() + " pieces whose models weigh "
              + AssistantStructureCommands.format(weight / 1024f / 1024f) + " MB in all: the 3D view draws their light version, and "
              + "restore_detail gives the full one back")
          + " (models of " + AssistantStructureCommands.format((float)(minimum / 1024)) + " KB or more)"
          + (waiting.isEmpty() ? "" : ". These have no reduced version yet: " + waiting + ". It is made by 3D view > Generate model "
              + "LOD cache, and by itself when a home is opened"));
    } else if ("find_duplicates".equals(action)) {
      findDuplicates(command, notes);
    } else if ("find_floating".equals(action)) {
      findFloating(command, notes);
    } else if ("move".equals(action) || "rotate".equals(action) || "resize".equals(action)
        || "set_color".equals(action) || "set_elevation".equals(action)
        || "set_visible".equals(action) || "rename".equals(action)
        || "reduce_detail".equals(action) || "restore_detail".equals(action)) {
      modify(action, command, tally, notes);
    } else if ("delete".equals(action) || "remove".equals(action)) {
      delete(command, tally);
    } else if (!this.plantCommands.apply(action, command, tally, notes)
               && !this.terrainCommands.apply(action, command, tally, notes)
               && !this.outdoorCommands.apply(action, command, tally, notes)
               && !this.gisCommands.apply(action, command, tally, notes)
               && !this.photoCommands.apply(action, command, tally, notes)
               && !this.structureCommands.apply(action, command, tally, notes)
               && !this.ceilingCommands.apply(action, command, tally, notes)
               && !this.shapeCommands.apply(action, command, tally, notes)
               && !this.buildingCommands.apply(action, command, tally, notes)
               && !this.onlineModels.apply(action, command, tally, notes)
               && !this.objectCommands.apply(action, command, tally, notes)
               && !this.layerCommands.apply(action, command, tally, notes)
               && !this.libraryCommands.apply(action, command, tally, notes)
               && !this.designCommands.apply(action, command, tally, notes)
               && !this.siteCommands.apply(action, command, tally, notes)
               && !this.arrangeCommands.apply(action, command, tally, notes)
               && !this.fenceCommands.apply(action, command, tally, notes)
               && !this.gardenCommands.apply(action, command, tally, notes)
               && !this.scheduleCommands.apply(action, command, tally, notes)
               && !this.sceneCommands.apply(action, command, tally, notes)
               && !this.wallFinishCommands.apply(action, command, tally, notes)
               && !this.railingCommands.apply(action, command, tally, notes)) {
      this.planCommands.apply(action, command, tally, notes);
    }
    // Unknown actions are ignored so a single bad command doesn't break a turn
  }

  /**
   * Runs a <code>search_catalog</code> command and records its matches as a note,
   * which the multi-step loop reports back to the model.
   */
  private void searchCatalogCommand(AssistantCommand command, List<String> notes) {
    String query = command.getString("query");
    if (query == null) {
      query = command.getString("name");
    }
    if (query == null || query.trim().length() == 0) {
      return;
    }
    List<CatalogMatch> matches = searchCatalog(query, false, MAX_SEARCH_RESULTS);
    StringBuilder note = new StringBuilder("Catalog search \"").append(query.trim()).append("\": ");
    if (matches.isEmpty()) {
      note.append("no matches");
    } else {
      for (int i = 0; i < matches.size(); i++) {
        if (i > 0) {
          note.append(", ");
        }
        CatalogMatch match = matches.get(i);
        note.append('"').append(match.piece.getName()).append('"')
            .append(" (").append(match.categoryName);
        if (match.piece.isDoorOrWindow()) {
          note.append(", door/window");
        }
        note.append(')');
      }
    }
    notes.add(note.toString());
  }

  /**
   * Applies a property change (move/rotate/resize/recolor/...) to the items the
   * command targets, posting a single snapshot-based undoable edit so the change
   * is reverted with the rest of the turn.
   */
  private void modify(String action, AssistantCommand command, int [] tally, List<String> notes) {
    boolean detailAction = "reduce_detail".equals(action) || "restore_detail".equals(action);
    List<Selectable> targets;
    if (detailAction && "all".equalsIgnoreCase(String.valueOf(command.getString("target")))) {
      // "all" is only honored for the reversible detail toggles
      targets = new ArrayList<Selectable>(this.home.getFurniture());
    } else {
      targets = resolveTargets(command);
    }
    if (targets.isEmpty()) {
      return;
    }
    List<String> missingReducedModels = new ArrayList<String>();
    List<ItemState> before = captureStates(targets);
    int changed = 0;
    for (Selectable item : targets) {
      if (applyModification(action, command, item, missingReducedModels)) {
        changed++;
      }
    }
    if (!missingReducedModels.isEmpty()) {
      notes.add("No reduced model exists yet for " + join(missingReducedModels)
          + "; run 3D view > Generate model LOD cache, save, then ask again");
    }
    if (changed > 0) {
      List<ItemState> after = captureStates(targets);
      beginTurnUpdate();
      this.homeController.getUndoableEditSupport().postEdit(
          new AssistantModificationUndoableEdit(before, after));
      tally [4] += changed;
    }
  }

  private boolean applyModification(String action, AssistantCommand command, Selectable item,
                                    List<String> missingReducedModels) {
    if ("reduce_detail".equals(action)) {
      if (item instanceof HomePieceOfFurniture) {
        HomePieceOfFurniture piece = (HomePieceOfFurniture)item;
        if (piece.getModel() != null && this.home.getModelLOD(piece.getModel()) != null) {
          if (!ModelLOD.isReducedDetailInView(piece)) {
            piece.setProperty(ModelLOD.LOW_POLY_PROPERTY, "true");
            return true;
          }
        } else {
          missingReducedModels.add(piece.getName() != null ? piece.getName() : "Unnamed piece");
        }
      }
      return false;
    } else if ("restore_detail".equals(action)) {
      if (item instanceof HomePieceOfFurniture
          && ModelLOD.isReducedDetailDisplayed((HomePieceOfFurniture)item, this.home)) {
        // Stored to keep the original model when reduced models are chosen automatically
        ((HomePieceOfFurniture)item).setProperty(ModelLOD.LOW_POLY_PROPERTY, "false");
        return true;
      }
      return false;
    } else if ("move".equals(action)) {
      return moveItem(command, item);
    } else if ("rotate".equals(action)) {
      return rotateItem(command, item);
    } else if ("resize".equals(action)) {
      return resizeItem(command, item);
    } else if ("set_color".equals(action)) {
      if (item instanceof HomePieceOfFurniture) {
        Integer color = parseColor(command.getString("color"));
        if (color != null && ((HomePieceOfFurniture)item).isTexturable()) {
          ((HomePieceOfFurniture)item).setColor(color);
          return true;
        }
      } else if (item instanceof Wall || item instanceof Room) {
        Integer color = parseColor(command.getString("color"));
        String part = command.getString("part");
        if (color == null) {
          return false;
        }
        // A color replaces the texture of the same surface
        if (item instanceof Wall) {
          Wall wall = (Wall)item;
          if (!"right".equalsIgnoreCase(part)) {
            wall.setLeftSideColor(color);
            wall.setLeftSideTexture(null);
          }
          if (!"left".equalsIgnoreCase(part)) {
            wall.setRightSideColor(color);
            wall.setRightSideTexture(null);
          }
        } else if ("ceiling".equalsIgnoreCase(part)) {
          ((Room)item).setCeilingColor(color);
          ((Room)item).setCeilingTexture(null);
        } else {
          ((Room)item).setFloorColor(color);
          ((Room)item).setFloorTexture(null);
        }
        return true;
      }
    } else if ("set_elevation".equals(action)) {
      if (item instanceof HomePieceOfFurniture && command.has("elevation")) {
        double elevation = command.getDouble("elevation", Double.NaN);
        if (Double.isNaN(elevation) || !sizeSane(elevation)) {
          return false;
        }
        ((HomePieceOfFurniture)item).setElevation((float)elevation);
        ((HomePieceOfFurniture)item).setProperty(BELOW_FLOOR_PROPERTY, elevation < 0 ? "true" : null);
        ((HomePieceOfFurniture)item).setProperty(OUTDOOR_PROPERTY, null);
        return true;
      } else if (item instanceof HomePieceOfFurniture && command.getBoolean("on_terrain", false)) {
        HomePieceOfFurniture piece = (HomePieceOfFurniture)item;
        Float height = this.shapeCommands.getTerrainHeight(piece.getX(), piece.getY());
        if (height == null) {
          // Out of the terrain: the height of its closest edge
          float [] nearest = this.shapeCommands.getNearestTerrainHeight(piece.getX(), piece.getY());
          if (nearest == null) {
            warn("The home has no terrain: the elevation of " + getId(piece) + " didn't change. set_terrain builds the ground");
            return false;
          }
          height = nearest [0];
          warn(getId(piece) + " is " + AssistantStructureCommands.format(nearest [1]) + " cm out of the terrain: it was put at the height "
              + "of the closest edge, " + AssistantStructureCommands.format(nearest [0]) + " cm");
        }
        double offset = command.getDouble("offset", 0);
        height = height + (float)(sizeSane(offset) ? offset : 0);
        piece.setElevation(height - (piece.getLevel() != null ? piece.getLevel().getElevation() : 0));
        if (command.getBoolean("align_to_slope", false)) {
          // Tilted as the ground under it, around one of its axes
          double angle = piece.getAngle();
          float halfDepth = Math.max(10, piece.getDepth() / 2);
          float halfWidth = Math.max(10, piece.getWidth() / 2);
          Float front = this.shapeCommands.getTerrainHeight(piece.getX() - (float)Math.sin(angle) * halfDepth, piece.getY() + (float)Math.cos(angle) * halfDepth);
          Float back = this.shapeCommands.getTerrainHeight(piece.getX() + (float)Math.sin(angle) * halfDepth, piece.getY() - (float)Math.cos(angle) * halfDepth);
          Float right = this.shapeCommands.getTerrainHeight(piece.getX() + (float)Math.cos(angle) * halfWidth, piece.getY() + (float)Math.sin(angle) * halfWidth);
          Float left = this.shapeCommands.getTerrainHeight(piece.getX() - (float)Math.cos(angle) * halfWidth, piece.getY() - (float)Math.sin(angle) * halfWidth);
          if (!piece.isHorizontallyRotatable()) {
            warn(getId(piece) + " can't be tilted: it stays upright");
          } else if (front != null && back != null && right != null && left != null) {
            double limit = Math.toRadians(Math.max(0, Math.min(45, command.getDouble("max_tilt", 20))));
            double pitch = Math.atan2(front - back, halfDepth * 2);
            double roll = -Math.atan2(right - left, halfWidth * 2);
            if (Math.abs(pitch) >= Math.abs(roll)) {
              piece.setPitch((float)Math.max(-limit, Math.min(limit, pitch)));
              piece.setRoll(0);
            } else {
              piece.setRoll((float)Math.max(-limit, Math.min(limit, roll)));
              piece.setPitch(0);
            }
            if (Math.max(Math.abs(pitch), Math.abs(roll)) > limit) {
              warn(getId(piece) + " stands on a slope of " + AssistantStructureCommands.format((float)Math.toDegrees(
                  Math.max(Math.abs(pitch), Math.abs(roll)))) + " degrees: it is tilted by " + AssistantStructureCommands.format(
                  (float)Math.toDegrees(limit)) + " degrees at most (\"max_tilt\")");
            }
          }
        }
        // A tree or a car on the ground isn't furniture out of its room
        piece.setProperty(OUTDOOR_PROPERTY, "true");
        return true;
      }
    } else if ("set_visible".equals(action)) {
      if (item instanceof HomePieceOfFurniture && command.has("visible")) {
        ((HomePieceOfFurniture)item).setVisible(command.getBoolean("visible", true));
        return true;
      }
    } else if ("rename".equals(action)) {
      String name = command.getString("name");
      if (name != null) {
        if (item instanceof HomePieceOfFurniture) {
          ((HomePieceOfFurniture)item).setName(name);
          return true;
        } else if (item instanceof Room) {
          ((Room)item).setName(name);
          return true;
        }
      }
    }
    return false;
  }

  private boolean moveItem(AssistantCommand command, Selectable item) {
    if (!(item instanceof HomePieceOfFurniture || item instanceof Wall || item instanceof Room)) {
      // Other selectable items (labels, dimension lines, compass, cameras...)
      // aren't snapshot for undo, so they are left alone
      return false;
    }
    if (command.has("dx") || command.has("dy")) {
      double dx = command.getDouble("dx", 0);
      double dy = command.getDouble("dy", 0);
      if (!coordinateSane(dx) || !coordinateSane(dy)) {
        return false;
      }
      item.move((float)dx, (float)dy);
      return true;
    } else if (item instanceof HomePieceOfFurniture && (command.has("x") || command.has("y"))) {
      HomePieceOfFurniture piece = (HomePieceOfFurniture)item;
      double x = command.getDouble("x", piece.getX());
      double y = command.getDouble("y", piece.getY());
      if (!coordinateSane(x) || !coordinateSane(y)) {
        return false;
      }
      piece.setX((float)x);
      piece.setY((float)y);
      return true;
    }
    return false;
  }

  private boolean rotateItem(AssistantCommand command, Selectable item) {
    if (!(item instanceof HomePieceOfFurniture)) {
      return false;
    }
    HomePieceOfFurniture piece = (HomePieceOfFurniture)item;
    boolean changed = false;
    if (command.has("by")) {
      piece.setAngle(piece.getAngle() + (float)Math.toRadians(command.getDouble("by", 0)));
      changed = true;
    } else if (command.has("angle")) {
      piece.setAngle((float)Math.toRadians(command.getDouble("angle", 0)));
      changed = true;
    }
    if ((command.has("pitch") || command.has("roll")) && piece.isHorizontallyRotatable()) {
      // A piece is tilted around one horizontal axis at a time, as in its modification dialog
      double pitch = command.getDouble("pitch", Double.NaN);
      double roll = command.getDouble("roll", Double.NaN);
      if (!Double.isNaN(pitch) && !Double.isInfinite(pitch)
          && (pitch % 360 != 0 || Double.isNaN(roll) || roll % 360 == 0)) {
        piece.setPitch((float)Math.toRadians(pitch));
        piece.setRoll(0);
        changed = true;
      } else if (!Double.isNaN(roll) && !Double.isInfinite(roll)) {
        piece.setRoll((float)Math.toRadians(roll));
        piece.setPitch(0);
        changed = true;
      }
    }
    return changed;
  }

  private boolean resizeItem(AssistantCommand command, Selectable item) {
    boolean changed = false;
    if (item instanceof HomePieceOfFurniture) {
      HomePieceOfFurniture piece = (HomePieceOfFurniture)item;
      if (!piece.isResizable()) {
        return false;
      }
      double width = command.getDouble("width", Double.NaN);
      if (!Double.isNaN(width) && width > 0 && sizeSane(width)) {
        piece.setWidth((float)width);
        changed = true;
      }
      double depth = command.getDouble("depth", Double.NaN);
      if (!Double.isNaN(depth) && depth > 0 && sizeSane(depth)) {
        piece.setDepth((float)depth);
        changed = true;
      }
      double height = command.getDouble("height", Double.NaN);
      if (!Double.isNaN(height) && height > 0 && sizeSane(height)) {
        piece.setHeight((float)height);
        changed = true;
      }
    } else if (item instanceof Wall) {
      Wall wall = (Wall)item;
      double thickness = command.getDouble("thickness", Double.NaN);
      if (!Double.isNaN(thickness) && thickness > 0 && sizeSane(thickness)) {
        wall.setThickness((float)thickness);
        changed = true;
      }
      double height = command.getDouble("height", Double.NaN);
      if (!Double.isNaN(height) && height > 0 && sizeSane(height)) {
        wall.setHeight(Float.valueOf((float)height));
        changed = true;
      }
    }
    return changed;
  }

  private void delete(AssistantCommand command, int [] tally) {
    List<Selectable> targets = resolveTargets(command);
    if (targets.isEmpty()) {
      return;
    }
    // Count and delete only what is really deletable and still in the home
    List<Selectable> deletable = new ArrayList<Selectable>(targets.size());
    for (Selectable item : targets) {
      if (isInHome(item)
          && !(item instanceof Compass || item instanceof Camera)
          && (!(item instanceof HomePieceOfFurniture)
              || this.homeController.getPlanController().isPieceOfFurnitureDeletable((HomePieceOfFurniture)item))) {
        deletable.add(item);
      }
    }
    if (deletable.isEmpty()) {
      return;
    }
    beginTurnUpdate();
    this.homeController.getPlanController().deleteItems(deletable);
    tally [5] += deletable.size();
  }

  /**
   * Resolves the items a command targets, by stable id (<code>F#</code>/<code>W#</code>/
   * <code>R#</code> matching {@link HomeAssistantContext}), by the literal
   * <code>selection</code> target, or by name (the <code>names</code> field).
   */
  List<Selectable> resolveTargets(AssistantCommand command) {
    List<Selectable> targets = new ArrayList<Selectable>();
    List<String> tokens = new ArrayList<String>();
    String singleId = command.getString("id");
    if (singleId != null) {
      tokens.add(singleId);
    }
    tokens.addAll(command.getStringList("ids"));
    String target = command.getString("target");
    if (target != null) {
      tokens.add(target);
    }
    boolean selectionRequested = false;
    for (String token : tokens) {
      if (token == null) {
        continue;
      }
      String trimmed = token.trim();
      if (trimmed.equalsIgnoreCase("selection") || trimmed.equalsIgnoreCase("selected")) {
        selectionRequested = true;
      } else {
        Selectable item = resolveId(trimmed);
        if (item != null && !targets.contains(item)) {
          targets.add(item);
        } else if (item == null && this.turnUnresolvedIds != null
                   && trimmed.matches("[FWRPfwrp]\\s*\\d+")
                   && !this.turnUnresolvedIds.contains(trimmed.toUpperCase(Locale.ENGLISH).replace(" ", ""))) {
          this.turnUnresolvedIds.add(trimmed.toUpperCase(Locale.ENGLISH).replace(" ", ""));
        }
      }
    }
    if (selectionRequested) {
      for (Selectable item : this.home.getSelectedItems()) {
        if (!targets.contains(item)) {
          targets.add(item);
        }
      }
    }
    Object where = command.getParameters().get("where");
    if (where instanceof Map) {
      for (Selectable item : resolveWhere((Map<?, ?>)where)) {
        if (!targets.contains(item)) {
          targets.add(item);
        }
      }
    }
    List<String> names = command.getStringList("names");
    if (!names.isEmpty()) {
      for (HomePieceOfFurniture piece : this.home.getFurniture()) {
        if (piece.getName() != null && containsName(names, piece.getName()) && !targets.contains(piece)) {
          targets.add(piece);
        }
      }
      for (Room room : this.home.getRooms()) {
        if (room.getName() != null && containsName(names, room.getName()) && !targets.contains(room)) {
          targets.add(room);
        }
      }
    }
    return targets;
  }

  /** The parameters where <code>last</code> stands for the item the commands before created. */
  private static final List<String> LAST_ID_KEYS = Arrays.asList("id", "ids", "fence", "fences", "item", "items", "target", "targets",
      "piece", "pieces", "of", "on", "around", "along", "follow", "relative_to", "attach_to", "room", "wall", "line", "tree", "trees",
      "structure", "deck", "parent", "opening", "roof", "stairs", "railing");

  private int [] getItemCounts() {
    return new int [] {this.home.getFurniture().size(), this.home.getWalls().size(), this.home.getRooms().size(),
        this.home.getPolylines().size(), this.home.getDimensionLines().size(), this.home.getLabels().size()};
  }

  /**
   * Returns the last item a command added to the home, or <code>null</code> if it added none.
   */
  private Object getLastCreated(int [] countsBefore) {
    List<?> [] lists = {this.home.getFurniture(), new ArrayList<Wall>(this.home.getWalls()), this.home.getRooms(),
        new ArrayList<Polyline>(this.home.getPolylines()), new ArrayList<Object>(this.home.getDimensionLines()),
        new ArrayList<Object>(this.home.getLabels())};
    for (int i = 0; i < lists.length; i++) {
      if (lists [i].size() > countsBefore [i]) {
        return lists [i].get(lists [i].size() - 1);
      }
    }
    return null;
  }

  /**
   * Replaces <code>"last"</code> and <code>"$last"</code> in the parameters of a command that name items
   * by the id of the last item created by the commands before it in the batch.
   */
  @SuppressWarnings("unchecked")
  private void replaceLastIds(AssistantCommand command, Object lastCreated) {
    try {
      for (Map.Entry<String, Object> entry : command.getParameters().entrySet()) {
        boolean idKey = LAST_ID_KEYS.contains(entry.getKey());
        Object value = entry.getValue();
        if (value instanceof String) {
          String id = getLastId((String)value, idKey, lastCreated);
          if (id != null) {
            entry.setValue(id);
          }
        } else if (value instanceof List) {
          List<Object> list = (List<Object>)value;
          for (int i = 0; i < list.size(); i++) {
            String id = list.get(i) instanceof String ? getLastId((String)list.get(i), idKey, lastCreated) : null;
            if (id != null) {
              list.set(i, id);
            }
          }
        }
      }
    } catch (UnsupportedOperationException ex) {
      // Parameters that can't be changed keep their value
    }
  }

  private String getLastId(String value, boolean idKey, Object lastCreated) {
    String text = value.trim();
    String part = "";
    int colon = text.indexOf(':');
    if (colon > 0) {
      // As in "last:end", a point of the last fence
      part = text.substring(colon);
      text = text.substring(0, colon).trim();
    }
    if (!text.equals("$last") && !(idKey && text.equalsIgnoreCase("last"))) {
      return null;
    } else if (lastCreated == null) {
      this.turnWarnings.add("\"" + value + "\" names the last item created by the commands before in the same batch, and none created one");
      return null;
    }
    HomeItemIds.ensureIds(this.home);
    String id = getId(lastCreated);
    return id != null ? id + part : null;
  }

  /**
   * Resolves a single <code>F#</code>/<code>W#</code>/<code>R#</code> id to the item
   * at that 1-based index in the home's furniture, walls or rooms, or <code>null</code>.
   * The ordering matches the ids shown by {@link HomeAssistantContext}.
   */
  private Selectable resolveId(String token) {
    HomeObject item = HomeItemIds.find(this.home, token);
    if (item == null && HomeItemIds.isId(token)) {
      // An item added earlier in the turn
      HomeItemIds.ensureIds(this.home);
      item = HomeItemIds.find(this.home, token);
    }
    return item instanceof Selectable ? (Selectable)item : null;
  }

  /**
   * Returns the furniture, the walls and the rooms matching the criteria of
   * <code>where</code>: <code>level</code> (a name or an id <code>L#</code>),
   * <code>tag</code>, <code>name</code> (a part of it), <code>type</code>
   * and <code>bbox</code> (<code>[x1, y1, x2, y2]</code>, which contains the item).
   */
  List<Selectable> resolveWhere(Map<?, ?> where) {
    Map<Object, Object> criteria = new java.util.LinkedHashMap<Object, Object>(where);
    Object regex = criteria.remove("name_regex");
    Object createdBy = criteria.remove("created_by");
    if (criteria.get("box") != null && criteria.get("bbox") == null) {
      criteria.put("bbox", criteria.remove("box"));
    }
    List<String> unknown = new ArrayList<String>();
    for (Object key : criteria.keySet()) {
      if (!java.util.Arrays.asList("level", "tag", "name", "type", "bbox").contains(key)) {
        unknown.add(String.valueOf(key));
      }
    }
    if (!unknown.isEmpty()) {
      warn("\"where\" ignored " + unknown + ": its criteria are level, tag, name, name_regex, type, bbox (or box) and created_by");
      for (String key : unknown) {
        criteria.remove(key);
      }
    }
    java.util.regex.Pattern pattern = null;
    if (regex != null) {
      try {
        pattern = java.util.regex.Pattern.compile(regex.toString(), java.util.regex.Pattern.CASE_INSENSITIVE);
      } catch (java.util.regex.PatternSyntaxException ex) {
        warn("Ignored \"where\": \"name_regex\" isn't a regular expression (" + ex.getDescription() + ")");
        return new ArrayList<Selectable>();
      }
    }
    if ((pattern != null || createdBy != null) && criteria.isEmpty()) {
      criteria.put("type", "all_furniture,walls,rooms,polylines");
    }
    List<Selectable> items = resolveWhereItems(criteria);
    if (pattern != null || createdBy != null) {
      boolean agent = createdBy != null && !createdBy.toString().toLowerCase(Locale.ENGLISH).startsWith("u");
      for (java.util.Iterator<Selectable> it = items.iterator(); it.hasNext(); ) {
        Selectable item = it.next();
        String itemName = item instanceof HomePieceOfFurniture ? ((HomePieceOfFurniture)item).getName()
            : item instanceof Room ? ((Room)item).getName()
            : item instanceof Polyline ? ((Polyline)item).getProperty(AssistantSiteCommands.LINE_NAME_PROPERTY) : null;
        boolean byAgent = item instanceof HomeObject && "agent".equals(((HomeObject)item).getProperty(CREATED_BY_PROPERTY));
        if (pattern != null && (itemName == null || !pattern.matcher(itemName).find())
            || createdBy != null && byAgent != agent) {
          it.remove();
        }
      }
    }
    return items;
  }

  private List<Selectable> resolveWhereItems(Map<?, ?> where) {
    List<Selectable> items = new ArrayList<Selectable>();
    String levelToken = where.get("level") != null ? where.get("level").toString() : null;
    String tag = where.get("tag") != null ? where.get("tag").toString().trim() : null;
    // "Pine|Oak" matches the names that contain one of these texts
    String name = where.get("name") != null ? where.get("name").toString().trim().toLowerCase(Locale.ENGLISH) : null;
    List<String> typeTokens = new ArrayList<String>();
    if (where.get("type") instanceof List) {
      for (Object type : (List<?>)where.get("type")) {
        typeTokens.add(String.valueOf(type));
      }
    } else if (where.get("type") != null) {
      for (String type : where.get("type").toString().split(",")) {
        typeTokens.add(type);
      }
    }
    float [] bbox = null;
    if (where.get("bbox") instanceof List && ((List<?>)where.get("bbox")).size() == 4) {
      bbox = new float [4];
      for (int i = 0; i < 4; i++) {
        Object value = ((List<?>)where.get("bbox")).get(i);
        if (!(value instanceof Number)) {
          warn("Ignored \"where\": \"bbox\" must be [x1, y1, x2, y2]");
          return items;
        }
        bbox [i] = ((Number)value).floatValue();
      }
      bbox = new float [] {Math.min(bbox [0], bbox [2]), Math.min(bbox [1], bbox [3]),
                           Math.max(bbox [0], bbox [2]), Math.max(bbox [1], bbox [3])};
    } else if (where.get("bbox") != null) {
      warn("Ignored \"where\": \"bbox\" must be [x1, y1, x2, y2]");
      return items;
    }
    if (levelToken == null && tag == null && name == null && typeTokens.isEmpty() && bbox == null) {
      warn("Ignored \"where\": give at least one of \"level\", \"tag\", \"name\", \"type\" and \"bbox\"");
      return items;
    }
    List<Level> levels = null;
    if (levelToken != null) {
      levels = HomeItemIds.findLevels(this.home, levelToken);
      if (levels.isEmpty()) {
        warn("Ignored \"where\": there is no level \"" + levelToken + "\"");
        return items;
      }
    }
    boolean walls = false;
    boolean rooms = false;
    boolean polylines = false;
    boolean allFurniture = false;
    List<String> furnitureTypes = new ArrayList<String>();
    for (String typeToken : typeTokens) {
      String type = typeToken.trim().toLowerCase(Locale.ENGLISH);
      if (type.equals("walls") || type.equals("wall")) {
        walls = true;
      } else if (type.equals("rooms") || type.equals("room")) {
        rooms = true;
      } else if (type.equals("polylines") || type.equals("polyline") || type.equals("lines")) {
        polylines = true;
      } else if (type.equals("all_furniture") || type.equals("pieces")) {
        allFurniture = true;
      } else if (HomeItemTags.parseType(type) != null) {
        furnitureTypes.add(HomeItemTags.parseType(type));
      } else if (type.length() > 0) {
        warn("Ignored \"where\": unknown type \"" + typeToken.trim()
            + "\" (furniture, doors_and_windows, lights, stairs, groups, all_furniture, walls, rooms, polylines)");
        return items;
      }
    }
    if (typeTokens.isEmpty()) {
      // Tags are those of furniture
      allFurniture = true;
      walls = rooms = polylines = tag == null;
    }
    if (allFurniture || !furnitureTypes.isEmpty()) {
      for (HomePieceOfFurniture piece : HomeItemTags.getFurniture(this.home, tag, null)) {
        if ((allFurniture || furnitureTypes.contains(HomeItemTags.getType(piece)))
            && (levels == null || levels.contains(piece.getLevel()))
            && (name == null || matchesName(piece.getName(), name))
            && (bbox == null || piece.getX() >= bbox [0] && piece.getX() <= bbox [2]
                && piece.getY() >= bbox [1] && piece.getY() <= bbox [3])) {
          items.add(piece);
        }
      }
    }
    if (walls && tag == null && name == null) {
      for (Wall wall : this.home.getWalls()) {
        if ((levels == null || levels.contains(wall.getLevel()))
            && (bbox == null || isInside(new float [][] {{wall.getXStart(), wall.getYStart()},
                                                         {wall.getXEnd(), wall.getYEnd()}}, bbox))) {
          items.add(wall);
        }
      }
    }
    if (rooms && tag == null) {
      for (Room room : this.home.getRooms()) {
        if ((levels == null || levels.contains(room.getLevel()))
            && (name == null || matchesName(room.getName(), name))
            && (bbox == null || isInside(room.getPoints(), bbox))) {
          items.add(room);
        }
      }
    }
    if (polylines && tag == null) {
      for (Polyline polyline : this.home.getPolylines()) {
        if ((levels == null || levels.contains(polyline.getLevel()))
            && (name == null || matchesName(polyline.getProperty(AssistantSiteCommands.LINE_NAME_PROPERTY), name))
            && (bbox == null || isInside(polyline.getPoints(), bbox))) {
          items.add(polyline);
        }
      }
    }
    return items;
  }

  /**
   * Returns <code>true</code> if <code>name</code> contains <code>pattern</code>, a text in lower case
   * or several ones separated by <code>|</code>.
   */
  static boolean matchesName(String name, String pattern) {
    if (name == null) {
      return false;
    }
    String lowerName = name.toLowerCase(Locale.ENGLISH);
    for (String alternative : pattern.split("\\|")) {
      if (alternative.trim().length() > 0 && lowerName.indexOf(alternative.trim()) >= 0) {
        return true;
      }
    }
    return false;
  }

  private static boolean isInside(float [][] points, float [] bbox) {
    for (float [] point : points) {
      if (point [0] < bbox [0] || point [0] > bbox [2] || point [1] < bbox [1] || point [1] > bbox [3]) {
        return false;
      }
    }
    return true;
  }

  /**
   * Returns <code>true</code> if the given item of a kind the assistant edits
   * (furniture, wall, room) still belongs to the home; other kinds are assumed present.
   */
  private boolean isInHome(Selectable item) {
    if (item instanceof HomePieceOfFurniture) {
      return this.home.getFurniture().contains(item);
    } else if (item instanceof Wall) {
      return this.home.getWalls().contains(item);
    } else if (item instanceof Room) {
      return this.home.getRooms().contains(item);
    } else {
      return true;
    }
  }

  /**
   * Parses a color given as <code>#RRGGBB</code>, <code>0xRRGGBB</code> or a decimal
   * integer into an RGB {@link Integer}, or <code>null</code> if it can't be parsed.
   */
  static Integer parseColor(String text) {
    if (text == null) {
      return null;
    }
    String value = text.trim();
    int radix = 10;
    if (value.startsWith("#")) {
      value = value.substring(1);
      radix = 16;
    } else if (value.startsWith("0x") || value.startsWith("0X")) {
      value = value.substring(2);
      radix = 16;
    }
    try {
      return Integer.valueOf((int)(Long.parseLong(value, radix) & 0xFFFFFF));
    } catch (NumberFormatException ex) {
      return null;
    }
  }

  private static List<ItemState> captureStates(List<Selectable> items) {
    List<ItemState> states = new ArrayList<ItemState>(items.size());
    for (Selectable item : items) {
      states.add(ItemState.capture(item));
    }
    return states;
  }

  private void addFurniture(AssistantCommand command, boolean doorOrWindow,
                            int [] tally, List<String> notFound, List<String> notes) {
    String name = command.getString("name");
    if (name == null || name.trim().length() == 0) {
      return;
    }
    CatalogPieceOfFurniture catalogPiece = findCatalogPiece(name, doorOrWindow);
    if (catalogPiece == null) {
      notFound.add(describeUnmatchedName(name));
      return;
    }
    double x = command.getDouble("x", Double.NaN);
    double y = command.getDouble("y", Double.NaN);
    double width = command.getDouble("width", Double.NaN);
    double depth = command.getDouble("depth", Double.NaN);
    double elevation = command.getDouble("elevation", Double.NaN);
    if (!coordinateSane(x) || !coordinateSane(y)
        || !sizeSane(width) || !sizeSane(depth) || !sizeSane(elevation)) {
      notes.add("Ignored add_furniture \"" + name + "\" with out-of-range values");
      return;
    }
    HomePieceOfFurniture piece =
        this.homeController.getFurnitureController().createHomePieceOfFurniture(catalogPiece);
    if (!Double.isNaN(x)) {
      piece.setX((float)x);
    }
    if (!Double.isNaN(y)) {
      piece.setY((float)y);
    }
    piece.setAngle((float)Math.toRadians(command.getDouble("angle", 0)));
    if (piece.isResizable()) {
      if (!Double.isNaN(width) && width > 0) {
        piece.setWidth((float)width);
      }
      if (!Double.isNaN(depth) && depth > 0) {
        piece.setDepth((float)depth);
      }
    }
    if (!Double.isNaN(elevation)) {
      piece.setElevation((float)elevation);
    }
    double height = command.getDouble("height", Double.NaN);
    if (!Double.isNaN(height) && height > 0 && sizeSane(height) && piece.isResizable()) {
      piece.setHeight((float)height);
    }
    Level level = this.home.getSelectedLevel();
    if (command.getString("level") != null) {
      List<Level> levels = HomeItemIds.findLevels(this.home, command.getString("level"));
      if (levels.isEmpty()) {
        notes.add("Ignored add_furniture \"" + name + "\": there is no level \"" + command.getString("level") + "\"");
        return;
      }
      level = levels.get(0);
    }
    piece.setLevel(level);
    Integer color = parseColor(command.getString("color"));
    if (command.getString("color") != null && (color == null || !piece.isTexturable())) {
      warn(color == null ? "add_furniture \"" + name + "\": \"color\" must be written #RRGGBB"
          : "add_furniture \"" + name + "\": this piece can't be colored");
    } else if (color != null) {
      piece.setColor(color);
    }
    String displayName = command.getString("name_override") != null ? command.getString("name_override") : command.getString("display_name");
    if (displayName != null && displayName.trim().length() > 0) {
      piece.setName(displayName.trim());
    }
    if (command.getBoolean("mirrored", false) && piece.isResizable()) {
      piece.setModelMirrored(true);
    }
    if (command.has("tags")) {
      List<String> tags = new ArrayList<String>();
      for (String tag : command.getStringList("tags")) {
        tags.addAll(HomeItemTags.parseTags(tag));
      }
      if (!tags.isEmpty()) {
        piece.setProperty(HomeItemTags.TAGS_PROPERTY, HomeItemTags.formatTags(tags));
      }
    }
    boolean onTerrain = command.has("on_terrain") ? command.getBoolean("on_terrain", false)
        : Double.isNaN(elevation) && !doorOrWindow && !"false".equals(this.home.getProperty(OUTDOOR_ON_TERRAIN_PROPERTY))
            && isOutdoorPlace(piece.getX(), piece.getY());
    if (onTerrain) {
      Float ground = this.shapeCommands.getTerrainHeight(piece.getX(), piece.getY());
      if (ground == null && command.has("on_terrain")) {
        float [] nearest = this.shapeCommands.getNearestTerrainHeight(piece.getX(), piece.getY());
        if (nearest != null) {
          ground = nearest [0];
          warn("add_furniture \"" + name + "\" is " + AssistantStructureCommands.format(nearest [1])
              + " cm out of the terrain: it was put at the height of the closest edge, " + AssistantStructureCommands.format(nearest [0]) + " cm");
        } else {
          warn("add_furniture \"" + name + "\": the home has no terrain, the piece stands at the elevation "
              + AssistantStructureCommands.format(piece.getElevation()) + " cm");
        }
      }
      if (ground != null) {
        double offset = command.getDouble("offset", 0);
        piece.setElevation(ground + (float)(sizeSane(offset) ? offset : 0) - (level != null ? level.getElevation() : 0));
        piece.setProperty(OUTDOOR_PROPERTY, "true");
      }
    }
    warnUnknownKeys(command, ADD_FURNITURE_KEYS);
    beginTurnUpdate();
    Level selectedLevel = this.home.getSelectedLevel();
    if (level != null && level != selectedLevel) {
      this.home.setSelectedLevel(level);
    }
    this.homeController.getFurnitureController().addFurniture(Collections.singletonList(piece));
    if (this.home.getSelectedLevel() != selectedLevel && selectedLevel != null) {
      this.home.setSelectedLevel(selectedLevel);
    }
    if (doorOrWindow || catalogPiece.isDoorOrWindow()) {
      tally [1]++;
    } else {
      tally [0]++;
    }
  }

  /**
   * Returns <code>true</code> if a terrain covers a point that is in no room: a place where
   * what is added stands on the ground.
   */
  private boolean isOutdoorPlace(float x, float y) {
    if (this.shapeCommands.getTerrainHeight(x, y) == null) {
      return false;
    }
    for (Room room : this.home.getRooms()) {
      if (room.containsPoint(x, y, 0)) {
        return false;
      }
    }
    return true;
  }

  /**
   * Warns about the keys of a command that it doesn't read.
   */
  void warnUnknownKeys(AssistantCommand command, List<String> knownKeys) {
    List<String> unknown = new ArrayList<String>();
    for (String key : command.getParameters().keySet()) {
      if (!knownKeys.contains(key)) {
        unknown.add(key);
      }
    }
    if (!unknown.isEmpty()) {
      List<String> valid = new ArrayList<String>(knownKeys);
      valid.remove("action");
      warn("Warning: " + command.getAction() + " ignored " + (unknown.size() == 1 ? "the key " : "the keys ") + unknown
          + ". Its keys: " + valid);
    }
  }

  /**
   * Changes at once the place, the size, the angle, the elevation, the color, the name, the tags,
   * the level and the visibility of furniture.
   */
  private void modifyFurniture(AssistantCommand command, int [] tally, List<String> notFound, List<String> notes) {
    List<Selectable> targets = new ArrayList<Selectable>();
    for (Selectable item : resolveTargets(command)) {
      if (item instanceof HomePieceOfFurniture) {
        targets.add(item);
      }
    }
    warnUnknownKeys(command, MODIFY_FURNITURE_KEYS);
    if (targets.isEmpty()) {
      notes.add("Couldn't run modify_furniture (no piece of furniture matches: give \"id\", \"ids\" or \"where\")");
      return;
    }
    // Each kind of change is the command that already makes it
    String [][] changes = {
        {"move_to_level", "level"}, {"resize", "width", "depth", "height"}, {"move", "x", "y"}, {"move", "dx", "dy"},
        {"rotate", "angle", "by", "pitch", "roll"}, {"set_elevation", "elevation", "on_terrain", "offset", "align_to_slope", "max_tilt"},
        {"set_color", "color"}, {"set_texture", "texture"}, {"set_visible", "visible"}, {"rename", "name"},
        {"set_tags", "tags"}, {"add_tags", "add_tags"}, {"remove_tags", "remove_tags"}};
    List<String> ids = new ArrayList<String>();
    for (Selectable item : targets) {
      ids.add(getId(item));
    }
    int modified = tally [4];
    List<String> done = new ArrayList<String>();
    for (String [] change : changes) {
      Map<String, Object> parameters = new java.util.LinkedHashMap<String, Object>();
      for (int i = 1; i < change.length; i++) {
        if (command.has(change [i])) {
          // add_tags and remove_tags are read as the tags of these commands
          parameters.put(change [i].endsWith("_tags") ? "tags" : change [i], command.getParameters().get(change [i]));
        }
      }
      if (parameters.isEmpty() || parameters.size() == 1 && parameters.containsKey("offset")) {
        continue;
      }
      parameters.put("ids", ids);
      int count = tally [4];
      int noteCount = notes.size();
      applyCommand(new AssistantCommand(change [0], parameters), tally, notFound, notes);
      if (tally [4] > count) {
        String what = change [0].equals("move_to_level") ? "level" : change [0].equals("resize") ? "size" : change [0].equals("move") ? "place"
            : change [0].equals("rotate") ? "angle" : change [0].equals("rename") ? "name" : change [0].replace("set_", "").replace("_", " ");
        if (!done.contains(what)) {
          done.add(what);
        }
      } else if (notes.size() == noteCount) {
        List<String> keys = new ArrayList<String>(parameters.keySet());
        keys.remove("ids");
        warn("modify_furniture: " + keys + " changed nothing (a piece that can't be resized or colored, or a value out of range)");
      }
    }
    if (done.isEmpty()) {
      if (command.getParameters().size() <= 2) {
        notes.add("Couldn't run modify_furniture (give what changes: x, y, dx, dy, angle, width, depth, height, elevation, "
            + "on_terrain, color, texture, visible, name, tags, level)");
      }
      return;
    }
    // Counted once
    tally [4] = modified + targets.size();
    StringBuilder text = new StringBuilder("Modified ");
    for (int i = 0; i < ids.size() && i < 12; i++) {
      text.append(i > 0 ? ", " : "").append(ids.get(i));
    }
    if (ids.size() > 12) {
      text.append(" and ").append(ids.size() - 12).append(" more");
    }
    notes.add(text.append(": ").append(join(done)).toString());
  }

  /**
   * Returns the key that tells two pieces show the same thing.
   */
  private static String getModelKey(HomePieceOfFurniture piece) {
    return (piece.getCatalogId() != null ? piece.getCatalogId() : piece.getName()) + "|" + Math.round(piece.getWidth()) + "|"
        + Math.round(piece.getDepth()) + "|" + Math.round(piece.getHeight());
  }

  /**
   * Reports the pieces that show the same model at the same place and angle, on any level.
   */
  private void findDuplicates(AssistantCommand command, List<String> notes) {
    double tolerance = command.getDouble("tolerance", 5);
    List<HomePieceOfFurniture> pieces = new ArrayList<HomePieceOfFurniture>();
    if (command.has("ids") || command.has("id") || command.has("where") || command.has("names")) {
      for (Selectable item : resolveTargets(command)) {
        if (item instanceof HomePieceOfFurniture) {
          pieces.add((HomePieceOfFurniture)item);
        }
      }
    } else {
      pieces.addAll(this.home.getFurniture());
    }
    Map<String, List<HomePieceOfFurniture>> byModel = new java.util.LinkedHashMap<String, List<HomePieceOfFurniture>>();
    for (HomePieceOfFurniture piece : pieces) {
      if (piece.getProperty(STRUCTURE_PROPERTY) != null) {
        continue;
      }
      List<HomePieceOfFurniture> same = byModel.get(getModelKey(piece));
      if (same == null) {
        byModel.put(getModelKey(piece), same = new ArrayList<HomePieceOfFurniture>());
      }
      same.add(piece);
    }
    StringBuilder text = new StringBuilder();
    int groups = 0;
    List<String> extraIds = new ArrayList<String>();
    Set<HomePieceOfFurniture> listed = new HashSet<HomePieceOfFurniture>();
    for (List<HomePieceOfFurniture> same : byModel.values()) {
      for (int i = 0; i < same.size(); i++) {
        HomePieceOfFurniture piece = same.get(i);
        if (listed.contains(piece)) {
          continue;
        }
        List<HomePieceOfFurniture> duplicates = new ArrayList<HomePieceOfFurniture>();
        for (int j = i + 1; j < same.size(); j++) {
          HomePieceOfFurniture other = same.get(j);
          double turn = Math.abs(Math.toDegrees(piece.getAngle() - other.getAngle())) % 360;
          if (!listed.contains(other) && Math.hypot(piece.getX() - other.getX(), piece.getY() - other.getY()) <= tolerance
              && Math.abs(getBottom(piece) - getBottom(other)) <= tolerance
              && Math.min(turn, 360 - turn) <= 1) {
            duplicates.add(other);
          }
        }
        if (!duplicates.isEmpty()) {
          listed.addAll(duplicates);
          if (groups++ < 40) {
            text.append("\n- ").append(getId(piece)).append(" \"").append(piece.getName()).append("\" at (")
                .append(Math.round(piece.getX())).append(", ").append(Math.round(piece.getY())).append(")")
                .append(piece.getLevel() != null ? " [" + piece.getLevel().getName() + "]" : "").append(" is repeated by ");
            for (int k = 0; k < duplicates.size(); k++) {
              HomePieceOfFurniture other = duplicates.get(k);
              text.append(k > 0 ? ", " : "").append(getId(other))
                  .append(other.getLevel() != null && other.getLevel() != piece.getLevel() ? " [" + other.getLevel().getName() + "]" : "")
                  .append(Math.abs(getBottom(other) - getBottom(piece)) > 1
                      ? " (" + Math.round(getBottom(other) - getBottom(piece)) + " cm higher)" : "");
            }
          }
          for (HomePieceOfFurniture other : duplicates) {
            extraIds.add("\"" + getId(other) + "\"");
          }
        }
      }
    }
    if (groups == 0) {
      notes.add("No piece repeats another one: same model, same size, within " + AssistantStructureCommands.format((float)tolerance)
          + " cm in the plan and in height, and at the same angle");
    } else {
      notes.add(groups + (groups == 1 ? " piece is" : " pieces are") + " repeated at the same place (" + extraIds.size()
          + " extra pieces):" + text + (groups > 40 ? "\n... and " + (groups - 40) + " more" : "")
          + "\nTo keep one of each: {\"action\":\"delete\",\"ids\":" + (extraIds.size() <= 200 ? extraIds.toString() : "[...]") + "}");
    }
  }

  /**
   * Returns the height of the bottom of a piece above the ground of the home.
   */
  private static float getBottom(HomePieceOfFurniture piece) {
    return piece.getElevation() + (piece.getLevel() != null ? piece.getLevel().getElevation() : 0);
  }

  /**
   * Returns the area within the outline of the walls of the home: their outer contours, at any level.
   */
  private Area getBuildingArea() {
    Area walls = new Area();
    for (Wall wall : this.home.getWalls()) {
      float [][] points = wall.getPoints();
      GeneralPath path = new GeneralPath();
      path.moveTo(points [0][0], points [0][1]);
      for (int i = 1; i < points.length; i++) {
        path.lineTo(points [i][0], points [i][1]);
      }
      path.closePath();
      walls.add(new Area(path));
    }
    // The outer contours of the walls, filled
    Area building = new Area();
    GeneralPath contour = null;
    float [] point = new float [6];
    for (PathIterator it = walls.getPathIterator(null, 2); !it.isDone(); it.next()) {
      int type = it.currentSegment(point);
      if (type == PathIterator.SEG_MOVETO) {
        contour = new GeneralPath();
        contour.moveTo(point [0], point [1]);
      } else if (type == PathIterator.SEG_LINETO) {
        contour.lineTo(point [0], point [1]);
      } else if (type == PathIterator.SEG_CLOSE && contour != null) {
        contour.closePath();
        building.add(new Area(contour));
        contour = null;
      }
    }
    return building;
  }

  /**
   * Reports the pieces standing outdoors that are above or under the ground.
   */
  private void findFloating(AssistantCommand command, List<String> notes) {
    double tolerance = command.getDouble("tolerance", 10);
    boolean terrain = false;
    for (HomePieceOfFurniture piece : this.home.getFurniture()) {
      terrain |= HomeTerrain.isTerrain(piece);
    }
    if (!terrain) {
      notes.add("The home has no terrain built by set_terrain: nothing to compare the pieces with");
      return;
    }
    List<HomePieceOfFurniture> pieces = new ArrayList<HomePieceOfFurniture>();
    if (command.has("ids") || command.has("id") || command.has("where") || command.has("names")) {
      for (Selectable item : resolveTargets(command)) {
        if (item instanceof HomePieceOfFurniture) {
          pieces.add((HomePieceOfFurniture)item);
        }
      }
    } else {
      pieces.addAll(this.home.getFurniture());
    }
    StringBuilder text = new StringBuilder();
    List<String> ids = new ArrayList<String>();
    int outside = 0;
    // A piece within the outline of the walls is indoors, even over a void with no room
    Area building = getBuildingArea();
    for (HomePieceOfFurniture piece : pieces) {
      if (piece.getProperty(STRUCTURE_PROPERTY) != null || HomeTerrain.isTerrain(piece) || piece.isDoorOrWindow()
          || !piece.isVisible()) {
        continue;
      }
      boolean indoors = false;
      for (Room room : this.home.getRooms()) {
        indoors |= room.containsPoint(piece.getX(), piece.getY(), 0);
      }
      if (indoors || building.contains(piece.getX(), piece.getY())) {
        continue;
      }
      Float ground = this.shapeCommands.getTerrainHeight(piece.getX(), piece.getY());
      if (ground == null) {
        outside++;
        continue;
      }
      float bottom = piece.getElevation() + (piece.getLevel() != null ? piece.getLevel().getElevation() : 0);
      float gap = bottom - ground;
      if (Math.abs(gap) > tolerance) {
        ids.add("\"" + getId(piece) + "\"");
        if (ids.size() <= 60) {
          text.append("\n- ").append(getId(piece)).append(" \"").append(piece.getName()).append("\" at (")
              .append(Math.round(piece.getX())).append(", ").append(Math.round(piece.getY())).append("): ")
              .append(AssistantStructureCommands.format(Math.abs(gap))).append(gap > 0 ? " cm above the ground" : " cm under the ground");
        }
      }
    }
    if (ids.isEmpty()) {
      notes.add("No piece outdoors is more than " + AssistantStructureCommands.format((float)tolerance) + " cm above or under the ground"
          + (outside > 0 ? " (" + outside + " pieces stand out of the terrain and weren't compared)" : ""));
    } else {
      notes.add(ids.size() + (ids.size() == 1 ? " piece outdoors isn't" : " pieces outdoors aren't") + " on the ground:" + text
          + (ids.size() > 60 ? "\n... and " + (ids.size() - 60) + " more" : "")
          + (outside > 0 ? "\n" + outside + " pieces stand out of the terrain and weren't compared" : "")
          + "\nTo put them on it: {\"action\":\"set_elevation\",\"ids\":" + (ids.size() <= 200 ? ids.toString() : "[...]")
          + ",\"on_terrain\":true}");
    }
  }

  /**
   * Describes a furniture name that didn't match the catalog, with the closest
   * catalog names so the model can retry with a real one.
   */
  private String describeUnmatchedName(String name) {
    List<CatalogMatch> closest = searchCatalog(name, false, 3);
    if (closest.isEmpty()) {
      return name;
    }
    StringBuilder description = new StringBuilder(name).append(" (closest catalog names: ");
    for (int i = 0; i < closest.size(); i++) {
      if (i > 0) {
        description.append(", ");
      }
      description.append('\'').append(closest.get(i).piece.getName()).append('\'');
    }
    return description.append(')').toString();
  }

  private void addRoom(AssistantCommand command, int [] tally, List<String> notes) {
    List<float []> points = command.getPoints("points");
    if (points.size() < 3) {
      return;
    }
    for (float [] point : points) {
      if (!coordinateSane(point [0]) || !coordinateSane(point [1])) {
        notes.add("Ignored add_room with out-of-range points");
        return;
      }
    }
    Room room = new Room(points.toArray(new float [points.size()][]));
    String name = command.getString("name");
    if (name != null && name.trim().length() > 0) {
      room.setName(name);
    }
    room.setLevel(this.home.getSelectedLevel());
    Integer floorColor = parseColor(command.getString("floor_color"));
    if (floorColor != null) {
      room.setFloorColor(floorColor);
    }
    if (command.has("ceiling_visible")) {
      room.setCeilingVisible(command.getBoolean("ceiling_visible", true));
    }
    if (command.has("floor_visible")) {
      room.setFloorVisible(command.getBoolean("floor_visible", true));
    }
    beginTurnUpdate();
    this.homeController.getPlanController().addRooms(Collections.singletonList(room));
    tally [2]++;
    if (command.has("floor_offset")) {
      // A floor above or under the one of the level
      try {
        String slab = this.shapeCommands.setRoomFloorOffset(room, command.getDouble("floor_offset", 0),
            command.getDouble("slab_thickness", 10));
        room.setFloorVisible(false);
        notes.add("Added the room " + getId(room) + (room.getName() != null ? " \"" + room.getName() + "\"" : "")
            + ": " + slab + ", and its floor at the height of the level is hidden");
      } catch (java.io.IOException ex) {
        notes.add("The room was added without \"floor_offset\" (" + ex.getMessage() + ")");
      }
    }
    if (command.has("ceiling") || command.has("flat_ceiling_at")) {
      // A ceiling under the slopes of the roof
      try {
        String ceiling = this.shapeCommands.setRoomCeiling(room, command.getString("ceiling"),
            command.getDouble("flat_ceiling_at", Double.NaN));
        if (room.getProperty(AssistantShapeCommands.ROOM_CEILING_PROPERTY) != null) {
          room.setCeilingVisible(false);
        }
        notes.add("Room " + getId(room) + (room.getName() != null ? " \"" + room.getName() + "\"" : "") + ": " + ceiling);
      } catch (java.io.IOException ex) {
        notes.add("The room was added with the ceiling of its level (" + ex.getMessage() + ")");
      }
    }
  }

  private void addWall(AssistantCommand command, int [] tally, List<String> notes) {
    float xStart = (float)command.getDouble("x1", Double.NaN);
    float yStart = (float)command.getDouble("y1", Double.NaN);
    float xEnd = (float)command.getDouble("x2", Double.NaN);
    float yEnd = (float)command.getDouble("y2", Double.NaN);
    if (Float.isNaN(xStart) || Float.isNaN(yStart) || Float.isNaN(xEnd) || Float.isNaN(yEnd)) {
      return;
    }
    if (!coordinateSane(xStart) || !coordinateSane(yStart)
        || !coordinateSane(xEnd) || !coordinateSane(yEnd)) {
      notes.add("Ignored add_wall with out-of-range coordinates");
      return;
    }
    float thickness = (float)command.getDouble("thickness", this.preferences.getNewWallThickness());
    float height = (float)command.getDouble("height", this.preferences.getNewWallHeight());
    if (!(thickness > 0) || !sizeSane(thickness)) {
      thickness = this.preferences.getNewWallThickness();
    }
    if (!(height > 0) || !sizeSane(height)) {
      height = this.preferences.getNewWallHeight();
    }
    Wall wall = new Wall(xStart, yStart, xEnd, yEnd, thickness, height);
    wall.setLevel(this.home.getSelectedLevel());
    beginTurnUpdate();
    this.homeController.getPlanController().addWalls(Collections.singletonList(wall));
    tally [3]++;
  }

  /** Returns <code>true</code> if the value is absent (NaN) or a plausible plan coordinate. */
  static boolean coordinateSane(double value) {
    return Double.isNaN(value) || Math.abs(value) <= MAX_COORDINATE_CM;
  }

  /** Returns <code>true</code> if the value is absent (NaN) or a plausible size/elevation. */
  static boolean sizeSane(double value) {
    return Double.isNaN(value) || Math.abs(value) <= MAX_SIZE_CM;
  }

  /**
   * Selects the items a command designates by ids, names or <code>where</code>, and tells what they are.
   */
  private void select(AssistantCommand command, List<String> notes) {
    List<Selectable> selection = resolveTargets(command);
    if (selection.isEmpty()) {
      notes.add("select found no item"
          + (command.getParameters().get("where") != null ? " matching \"where\"" : ""));
      return;
    }
    this.home.setSelectedItems(selection);
    StringBuilder text = new StringBuilder("Selected " + selection.size() + (selection.size() == 1 ? " item: " : " items: "));
    for (int i = 0; i < selection.size(); i++) {
      if (i == MAX_CREATED_IDS) {
        text.append(", and ").append(selection.size() - i).append(" more");
        break;
      }
      Selectable item = selection.get(i);
      text.append(i > 0 ? "; " : "").append(getId(item));
      if (item instanceof HomePieceOfFurniture) {
        HomePieceOfFurniture piece = (HomePieceOfFurniture)item;
        text.append(" \"").append(piece.getName()).append("\" at (").append(Math.round(piece.getX())).append(", ")
            .append(Math.round(piece.getY())).append(")");
      } else if (item instanceof Room) {
        text.append(" room \"").append(((Room)item).getName() != null ? ((Room)item).getName() : "").append('"');
      } else if (item instanceof Wall) {
        Wall wall = (Wall)item;
        text.append(" wall (").append(Math.round(wall.getXStart())).append(", ").append(Math.round(wall.getYStart()))
            .append(") to (").append(Math.round(wall.getXEnd())).append(", ").append(Math.round(wall.getYEnd())).append(")");
      } else if (item instanceof Polyline) {
        String name = ((Polyline)item).getProperty(AssistantSiteCommands.LINE_NAME_PROPERTY);
        text.append(" line").append(name != null ? " \"" + name + "\"" : "");
      }
      Level level = item instanceof com.eteks.sweethome3d.model.Elevatable ? ((com.eteks.sweethome3d.model.Elevatable)item).getLevel() : null;
      if (level != null && this.home.getLevels().size() > 1) {
        text.append(" [").append(level.getName()).append(']');
      }
    }
    notes.add(text.toString());
  }

  private static boolean containsName(List<String> names, String candidate) {
    for (String name : names) {
      if (name.equalsIgnoreCase(candidate)) {
        return true;
      }
    }
    return false;
  }

  /**
   * Returns the catalog piece whose name best matches <code>query</code>,
   * optionally restricted to doors and windows, or <code>null</code> if nothing
   * matches at all.
   */
  public CatalogPieceOfFurniture findCatalogPiece(String query, boolean doorOrWindow) {
    List<CatalogMatch> matches = searchCatalog(query, doorOrWindow, 1);
    return matches.isEmpty() ? null : matches.get(0).piece;
  }

  /**
   * Searches the furniture catalog for pieces matching <code>query</code>,
   * best match first. Matching is scored: an exact name beats a name containing
   * every query word, which beats substring and partial word matches; plural
   * "s" suffixes are ignored when comparing words.
   */
  public List<CatalogMatch> searchCatalog(String query, boolean doorOrWindow, int maxResults) {
    List<CatalogMatch> matches = new ArrayList<CatalogMatch>();
    if (query == null || this.preferences.getFurnitureCatalog() == null) {
      return matches;
    }
    String normalizedQuery = query.trim().toLowerCase();
    List<String> queryTokens = tokenize(normalizedQuery);
    for (FurnitureCategory category : this.preferences.getFurnitureCatalog().getCategories()) {
      for (CatalogPieceOfFurniture piece : category.getFurniture()) {
        if (doorOrWindow && !piece.isDoorOrWindow()) {
          continue;
        }
        String name = piece.getName();
        if (name == null) {
          continue;
        }
        int score = scoreMatch(name.toLowerCase(), normalizedQuery, queryTokens);
        if (score > 0) {
          matches.add(new CatalogMatch(piece, category.getName(), score));
        }
      }
    }
    Collections.sort(matches);
    if (matches.size() > maxResults) {
      return new ArrayList<CatalogMatch>(matches.subList(0, maxResults));
    }
    return matches;
  }

  /**
   * Scores how well a catalog piece <code>name</code> matches a query, both
   * already lower-case; 0 means no match. Word comparisons ignore a plural "s".
   */
  static int scoreMatch(String name, String query, List<String> queryTokens) {
    if (name.equals(query)) {
      return 1000;
    }
    List<String> nameTokens = tokenize(name);
    int matched = 0;
    for (String queryToken : queryTokens) {
      for (String nameToken : nameTokens) {
        if (tokensEqual(queryToken, nameToken)) {
          matched++;
          break;
        }
      }
    }
    int score;
    if (!queryTokens.isEmpty() && matched == queryTokens.size()) {
      // Every query word appears in the name ("table" matches "Round table")
      score = 500;
    } else if (name.contains(query)) {
      score = 400;
    } else if (query.contains(name)) {
      score = 350;
    } else if (matched > 0) {
      score = 100 + (200 * matched) / queryTokens.size();
    } else {
      return 0;
    }
    // Prefer concise names: "Door" beats "Sliding door" for the query "door"
    return score - Math.min(nameTokens.size(), 50);
  }

  private static boolean tokensEqual(String token1, String token2) {
    return token1.equals(token2)
        || singular(token1).equals(singular(token2));
  }

  private static String singular(String token) {
    return token.length() > 3 && token.endsWith("s")
        ? token.substring(0, token.length() - 1) : token;
  }

  /** Splits lower-case text into alphanumeric word tokens. */
  static List<String> tokenize(String text) {
    List<String> tokens = new ArrayList<String>();
    int start = -1;
    for (int i = 0; i <= text.length(); i++) {
      boolean wordChar = i < text.length() && Character.isLetterOrDigit(text.charAt(i));
      if (wordChar && start < 0) {
        start = i;
      } else if (!wordChar && start >= 0) {
        tokens.add(text.substring(start, i));
        start = -1;
      }
    }
    return tokens;
  }

  /**
   * A scored catalog search result, ordered best match first.
   */
  public static final class CatalogMatch implements Comparable<CatalogMatch> {
    final CatalogPieceOfFurniture piece;
    final String                  categoryName;
    final int                     score;

    CatalogMatch(CatalogPieceOfFurniture piece, String categoryName, int score) {
      this.piece = piece;
      this.categoryName = categoryName;
      this.score = score;
    }

    public int compareTo(CatalogMatch other) {
      if (this.score != other.score) {
        return other.score - this.score;
      }
      // Deterministic order between equal scores
      return this.piece.getName().compareTo(other.piece.getName());
    }
  }

  private String buildSummary(int [] tally, List<String> notFound, List<String> notes) {
    List<String> parts = new ArrayList<String>();
    addPart(parts, tally [0], "piece of furniture", "pieces of furniture");
    addPart(parts, tally [1], "door/window", "doors/windows");
    addPart(parts, tally [2], "room", "rooms");
    addPart(parts, tally [3], "wall", "walls");
    List<String> clauses = new ArrayList<String>();
    if (!parts.isEmpty()) {
      StringBuilder added = new StringBuilder("added ");
      for (int i = 0; i < parts.size(); i++) {
        if (i > 0) {
          added.append(i == parts.size() - 1 ? " and " : ", ");
        }
        added.append(parts.get(i));
      }
      clauses.add(added.toString());
    }
    if (tally [4] == 1) {
      clauses.add("modified 1 item");
    } else if (tally [4] > 1) {
      clauses.add("modified " + tally [4] + " items");
    }
    if (tally [5] == 1) {
      clauses.add("deleted 1 item");
    } else if (tally [5] > 1) {
      clauses.add("deleted " + tally [5] + " items");
    }
    StringBuilder summary = new StringBuilder();
    if (!clauses.isEmpty()) {
      summary.append("Applied changes: ");
      for (int i = 0; i < clauses.size(); i++) {
        if (i > 0) {
          summary.append(i == clauses.size() - 1 ? " and " : ", ");
        }
        summary.append(clauses.get(i));
      }
      summary.append(". Use Edit > Undo to revert.");
    }
    if (!notFound.isEmpty()) {
      if (summary.length() > 0) {
        summary.append('\n');
      }
      summary.append("Couldn't find furniture named: ").append(join(notFound)).append('.');
    }
    for (String note : notes) {
      if (summary.length() > 0) {
        summary.append('\n');
      }
      summary.append(note);
      if (!note.endsWith(".")) {
        summary.append('.');
      }
    }
    return summary.length() > 0 ? summary.toString() : null;
  }

  private static void addPart(List<String> parts, int count, String singular, String plural) {
    if (count == 1) {
      parts.add("1 " + singular);
    } else if (count > 1) {
      parts.add(count + " " + plural);
    }
  }

  private static String join(List<String> values) {
    StringBuilder builder = new StringBuilder();
    for (int i = 0; i < values.size(); i++) {
      if (i > 0) {
        builder.append(", ");
      }
      builder.append('"').append(values.get(i)).append('"');
    }
    return builder.toString();
  }

  /**
   * A snapshot of the mutable geometry and appearance of a single home item,
   * used to undo and redo the property changes the assistant makes.
   */
  private static final class ItemState {
    private final Selectable item;
    // Furniture
    private float     x, y, angle, width, depth, height, elevation, pitch, roll;
    private Integer   color;
    private boolean   visible;
    // Wall
    private float     xStart, yStart, xEnd, yEnd, thickness;
    private Float     wallHeight, wallHeightAtEnd, arcExtent;
    private Integer   topColor;
    private com.eteks.sweethome3d.model.Baseboard leftBaseboard, rightBaseboard;
    // Furniture properties the assistant changes
    private String    planVisibility;
    private String    outdoor;
    private String    belowFloor;
    // Room
    private float [][] points;
    private boolean    floorVisible, ceilingVisible, areaVisible;
    // Furniture or room
    private String    name;
    // Furniture reduced-detail flag (ModelLOD.LOW_POLY_PROPERTY)
    private String    lowPoly;
    // Appearance of furniture (texture), walls (left / right) and rooms (floor / ceiling)
    private Integer     color1, color2;
    private HomeTexture texture1, texture2;
    // Walls joined to a wall
    private Wall      wallAtStart, wallAtEnd;
    private Level     level;

    private ItemState(Selectable item) {
      this.item = item;
    }

    static ItemState capture(Selectable item) {
      ItemState state = new ItemState(item);
      if (item instanceof HomePieceOfFurniture) {
        HomePieceOfFurniture piece = (HomePieceOfFurniture)item;
        state.x = piece.getX();
        state.y = piece.getY();
        state.angle = piece.getAngle();
        state.width = piece.getWidth();
        state.depth = piece.getDepth();
        state.height = piece.getHeight();
        state.elevation = piece.getElevation();
        state.pitch = piece.getPitch();
        state.roll = piece.getRoll();
        state.color = piece.getColor();
        state.visible = piece.isVisible();
        state.name = piece.getName();
        state.lowPoly = piece.getProperty(ModelLOD.LOW_POLY_PROPERTY);
        state.planVisibility = piece.getProperty(FurniturePlanVisibility.PROPERTY);
        state.outdoor = piece.getProperty(OUTDOOR_PROPERTY);
        state.belowFloor = piece.getProperty(BELOW_FLOOR_PROPERTY);
        state.texture1 = piece.getTexture();
        state.level = piece.getLevel();
      } else if (item instanceof Wall) {
        Wall wall = (Wall)item;
        state.xStart = wall.getXStart();
        state.yStart = wall.getYStart();
        state.xEnd = wall.getXEnd();
        state.yEnd = wall.getYEnd();
        state.thickness = wall.getThickness();
        state.wallHeight = wall.getHeight();
        state.wallHeightAtEnd = wall.getHeightAtEnd();
        state.arcExtent = wall.getArcExtent();
        state.topColor = wall.getTopColor();
        state.leftBaseboard = wall.getLeftSideBaseboard();
        state.rightBaseboard = wall.getRightSideBaseboard();
        state.color1 = wall.getLeftSideColor();
        state.color2 = wall.getRightSideColor();
        state.texture1 = wall.getLeftSideTexture();
        state.texture2 = wall.getRightSideTexture();
        state.wallAtStart = wall.getWallAtStart();
        state.wallAtEnd = wall.getWallAtEnd();
        state.level = wall.getLevel();
      } else if (item instanceof Room) {
        Room room = (Room)item;
        state.name = room.getName();
        state.points = room.getPoints();
        state.floorVisible = room.isFloorVisible();
        state.ceilingVisible = room.isCeilingVisible();
        state.areaVisible = room.isAreaVisible();
        state.color1 = room.getFloorColor();
        state.color2 = room.getCeilingColor();
        state.texture1 = room.getFloorTexture();
        state.texture2 = room.getCeilingTexture();
        state.level = room.getLevel();
      } else if (item instanceof com.eteks.sweethome3d.model.Elevatable) {
        // Labels, dimension lines and polylines, moved from a level to an other
        state.level = ((com.eteks.sweethome3d.model.Elevatable)item).getLevel();
      }
      return state;
    }

    private static boolean same(Object value1, Object value2) {
      return value1 == value2 || value1 != null && value1.equals(value2);
    }

    void restore() {
      if (this.item instanceof HomePieceOfFurniture) {
        HomePieceOfFurniture piece = (HomePieceOfFurniture)this.item;
        // Write back only what differs: setters of groups propagate to their
        // children, and size/color setters throw on non resizable/texturable pieces
        if (piece.getX() != this.x) {
          piece.setX(this.x);
        }
        if (piece.getY() != this.y) {
          piece.setY(this.y);
        }
        if (piece.getAngle() != this.angle) {
          piece.setAngle(this.angle);
        }
        if (piece.isHorizontallyRotatable()) {
          // Before the size, which the plan computes again when a piece is tilted
          if (piece.getPitch() != this.pitch) {
            piece.setPitch(this.pitch);
          }
          if (piece.getRoll() != this.roll) {
            piece.setRoll(this.roll);
          }
        }
        if (piece.isResizable()) {
          if (piece.getWidth() != this.width) {
            piece.setWidth(this.width);
          }
          if (piece.getDepth() != this.depth) {
            piece.setDepth(this.depth);
          }
          if (piece.getHeight() != this.height) {
            piece.setHeight(this.height);
          }
        }
        if (piece.getElevation() != this.elevation) {
          piece.setElevation(this.elevation);
        }
        if (piece.isTexturable() && !same(piece.getColor(), this.color)) {
          piece.setColor(this.color);
        }
        if (piece.isVisible() != this.visible) {
          piece.setVisible(this.visible);
        }
        if (!same(piece.getName(), this.name)) {
          piece.setName(this.name);
        }
        if (!same(piece.getProperty(ModelLOD.LOW_POLY_PROPERTY), this.lowPoly)) {
          piece.setProperty(ModelLOD.LOW_POLY_PROPERTY, this.lowPoly);
        }
        if (!same(piece.getProperty(FurniturePlanVisibility.PROPERTY), this.planVisibility)) {
          piece.setProperty(FurniturePlanVisibility.PROPERTY, this.planVisibility);
        }
        if (!same(piece.getProperty(OUTDOOR_PROPERTY), this.outdoor)) {
          piece.setProperty(OUTDOOR_PROPERTY, this.outdoor);
        }
        if (!same(piece.getProperty(BELOW_FLOOR_PROPERTY), this.belowFloor)) {
          piece.setProperty(BELOW_FLOOR_PROPERTY, this.belowFloor);
        }
        if (piece.isTexturable() && piece.getTexture() != this.texture1) {
          piece.setTexture(this.texture1);
        }
        if (piece.getLevel() != this.level) {
          piece.setLevel(this.level);
        }
      } else if (this.item instanceof Wall) {
        Wall wall = (Wall)this.item;
        wall.setXStart(this.xStart);
        wall.setYStart(this.yStart);
        wall.setXEnd(this.xEnd);
        wall.setYEnd(this.yEnd);
        wall.setThickness(this.thickness);
        wall.setHeight(this.wallHeight);
        wall.setHeightAtEnd(this.wallHeightAtEnd);
        wall.setArcExtent(this.arcExtent);
        wall.setTopColor(this.topColor);
        wall.setLeftSideBaseboard(this.leftBaseboard);
        wall.setRightSideBaseboard(this.rightBaseboard);
        wall.setLeftSideColor(this.color1);
        wall.setRightSideColor(this.color2);
        wall.setLeftSideTexture(this.texture1);
        wall.setRightSideTexture(this.texture2);
        wall.setWallAtStart(this.wallAtStart);
        wall.setWallAtEnd(this.wallAtEnd);
        if (wall.getLevel() != this.level) {
          wall.setLevel(this.level);
        }
      } else if (this.item instanceof Room) {
        Room room = (Room)this.item;
        room.setName(this.name);
        if (this.points != null) {
          room.setPoints(this.points);
        }
        room.setFloorVisible(this.floorVisible);
        room.setCeilingVisible(this.ceilingVisible);
        room.setAreaVisible(this.areaVisible);
        room.setFloorColor(this.color1);
        room.setCeilingColor(this.color2);
        room.setFloorTexture(this.texture1);
        room.setCeilingTexture(this.texture2);
        if (room.getLevel() != this.level) {
          room.setLevel(this.level);
        }
      } else if (this.item instanceof com.eteks.sweethome3d.model.Label) {
        ((com.eteks.sweethome3d.model.Label)this.item).setLevel(this.level);
      } else if (this.item instanceof com.eteks.sweethome3d.model.DimensionLine) {
        ((com.eteks.sweethome3d.model.DimensionLine)this.item).setLevel(this.level);
      } else if (this.item instanceof com.eteks.sweethome3d.model.Polyline) {
        ((com.eteks.sweethome3d.model.Polyline)this.item).setLevel(this.level);
      }
    }
  }

  /**
   * Reverts or replays the assistant's property changes by restoring the
   * before/after {@link ItemState snapshots} captured around them.
   */
  private static final class AssistantModificationUndoableEdit extends AbstractUndoableEdit {
    private final List<ItemState> before;
    private final List<ItemState> after;

    AssistantModificationUndoableEdit(List<ItemState> before, List<ItemState> after) {
      this.before = before;
      this.after = after;
    }

    @Override
    public void undo() {
      super.undo();
      for (ItemState state : this.before) {
        state.restore();
      }
    }

    @Override
    public void redo() {
      super.redo();
      for (ItemState state : this.after) {
        state.restore();
      }
    }

    @Override
    public String getPresentationName() {
      return "AI assistant edit";
    }
  }
