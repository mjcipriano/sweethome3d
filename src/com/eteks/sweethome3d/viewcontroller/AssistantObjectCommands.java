/**
 * The commands of the design assistant that bring new objects into a home:
 * stairs between levels, furniture showing a picture, 3D models and textures
 * imported from files of this computer.
 * @author Sweet Home 3D
 */
class AssistantObjectCommands {
  /** Property set to <code>"true"</code> on the stairs generated by <code>add_stairs</code>. */
  static final String STAIRS_PROPERTY = "assistantStairs";
  /** The value of the <code>image</code> parameter designating the picture attached to the conversation. */
  static final String ATTACHED_IMAGE = "attached";

  private static final long   MAX_IMAGE_LENGTH = 20L * 1024 * 1024;
  private static final long   MAX_MODEL_LENGTH = 300L * 1024 * 1024;
  private static final int    DEFAULT_STAIRS_COLOR = 0xB8A38A;
  private static final int    DEFAULT_BOX_COLOR = 0xD8D8D8;
  private static final String IMPORTED_CATEGORY = "Imported";
  /** A staircase cuts the floors above it over its whole area. */
  private static final Pattern MODEL_NAME = Pattern.compile(".*\\.(obj|dae|3ds|kmz)$", Pattern.CASE_INSENSITIVE);

  private final Home                     home;
  private final UserPreferences          preferences;
  private final HomeController           homeController;
  private final AssistantCommandExecutor executor;

  AssistantObjectCommands(Home home, UserPreferences preferences, HomeController homeController,
                          AssistantCommandExecutor executor) {
    this.home = home;
    this.preferences = preferences;
    this.homeController = homeController;
    this.executor = executor;
  }

  /**
   * Runs <code>command</code> if it's one of the commands of this class and
   * returns <code>true</code> in that case.
   */
  boolean apply(String action, AssistantCommand command, int [] tally, List<String> notes) {
    try {
      if ("add_stairs".equals(action) || "add_staircase".equals(action)) {
        addStairs(command, tally, notes);
      } else if ("add_picture".equals(action) || "add_furniture_from_image".equals(action)) {
        addPicture(command, tally, notes);
      } else if ("import_furniture".equals(action) || "import_model".equals(action)) {
        importFurniture(command, tally, notes);
      } else if ("import_texture".equals(action)) {
        importTexture(command, tally, notes);
      } else {
        return false;
      }
    } catch (IOException ex) {
      notes.add("Couldn't run " + action + " (" + ex.getMessage() + ")");
    }
    return true;
  }

  // ---- Stairs ----

  /**
   * Adds a straight flight of stairs climbing from the selected level to the
   * next one, and cuts the floor above it.
   */
  private void addStairs(AssistantCommand command, int [] tally, List<String> notes) throws IOException {
    double x = command.getDouble("x", Double.NaN);
    double y = command.getDouble("y", Double.NaN);
    double width = command.getDouble("width", 90);
    if (Double.isNaN(x) || Double.isNaN(y) || !AssistantCommandExecutor.coordinateSane(x)
        || !AssistantCommandExecutor.coordinateSane(y) || !(width >= 40) || width > 500) {
      notes.add("Ignored add_stairs: x and y are required, and width must be between 40 and 500 cm");
      return;
    }
    Level level = this.home.getSelectedLevel();
    // Up to the floor of the next level, or by the height of a floor
    double rise = command.getDouble("rise", Double.NaN);
    Level levelAbove = null;
    if (level != null) {
      for (Level other : this.home.getLevels()) {
        if (other.getElevation() > level.getElevation() + 1
            && !isRoofLevel(other)
            && (levelAbove == null || other.getElevation() < levelAbove.getElevation())) {
          levelAbove = other;
        }
      }
    }
    if (Double.isNaN(rise)) {
      rise = levelAbove != null
          ? levelAbove.getElevation() - level.getElevation()
          : (level != null ? level.getHeight() : this.home.getWallHeight()) + this.preferences.getNewFloorThickness();
    }
    if (!(rise >= 30) || rise > 1000) {
      notes.add("Ignored add_stairs: the height to climb must be between 30 and 1000 cm");
      return;
    }
    int stepCount = AssistantGeneratedModel.getStepCount((float)rise);
    String shapeName = command.getString("shape");
    shapeName = shapeName != null ? shapeName.trim().toLowerCase(Locale.ENGLISH) : "";
    int shape = shapeName.startsWith("l") || shapeName.contains("quarter")
        ? AssistantGeneratedModel.STAIRS_L
        : (shapeName.startsWith("u") || shapeName.contains("half")
            ? AssistantGeneratedModel.STAIRS_U
            : AssistantGeneratedModel.STAIRS_STRAIGHT);
    if (stepCount < 4) {
      shape = AssistantGeneratedModel.STAIRS_STRAIGHT;
    }
    // Treads of 25 cm, unless a tread or the length of a straight flight is given
    double tread = command.getDouble("tread", 25);
    double length = command.getDouble("length", Double.NaN);
    if (shape == AssistantGeneratedModel.STAIRS_STRAIGHT && length >= stepCount * 15 && length <= 2000) {
      tread = length / stepCount;
    }
    if (!(tread >= 15) || tread > 125) {
      tread = 25;
    }
    boolean turnRight = !"left".equalsIgnoreCase(command.getString("turn"));
    String railing = command.getString("railing");
    railing = railing != null ? railing.trim().toLowerCase(Locale.ENGLISH) : "";
    boolean leftRail = "left".equals(railing) || "both".equals(railing) || "true".equals(railing);
    boolean rightRail = "right".equals(railing) || "both".equals(railing) || "true".equals(railing);
    Integer color = AssistantCommandExecutor.parseColor(command.getString("color"));
    AssistantGeneratedModel model = AssistantGeneratedModel.buildStairs((float)width, (float)tread,
        (float)rise, color != null ? color : DEFAULT_STAIRS_COLOR, shape, turnRight, leftRail, rightRail);
    String name = command.getString("name");
    HomePieceOfFurniture piece = new HomePieceOfFurniture(new CatalogPieceOfFurniture(
        name != null && name.trim().length() > 0 ? name.trim() : "Staircase",
        model.getIcon(), model.getModel(), model.getWidth(), model.getDepth(), model.getHeight(), true, false));
    piece.setX((float)x);
    piece.setY((float)y);
    piece.setAngle((float)Math.toRadians(command.getDouble("angle", 0)));
    piece.setLevel(level);
    piece.setStaircaseCutOutShape(model.getCutOutShape());
    piece.setProperty(STAIRS_PROPERTY, "true");
    piece.setProperty(AssistantGeneratedModel.STAIRS_FLIGHTS_PROPERTY, model.getFlights());
    this.executor.beginTurnUpdate();
    this.homeController.getFurnitureController().addFurniture(Collections.singletonList(piece));
    tally [0]++;
    notes.add("Added " + (shape == AssistantGeneratedModel.STAIRS_L ? "L-shaped stairs"
            : (shape == AssistantGeneratedModel.STAIRS_U ? "U-shaped stairs" : "stairs"))
        + " of " + stepCount + " steps" + (leftRail || rightRail ? " with a handrail" : "")
        + ", " + Math.round(width) + " cm wide, taking " + Math.round(model.getWidth()) + " x "
        + Math.round(model.getDepth()) + " cm on the floor, climbing " + Math.round(rise) + " cm"
        + (levelAbove != null
            ? " to the level \"" + levelAbove.getName() + "\", whose floor is cut out above them"
            : "; there is no level above yet (add_level creates one, and its floor will be cut out above the stairs)")
        + ". The bottom step is at the front of the piece (toward +y at angle 0)");
  }

  private boolean isRoofLevel(Level level) {
    for (HomePieceOfFurniture piece : this.home.getFurniture()) {
      if (piece.getLevel() == level
          && "true".equals(piece.getProperty(AssistantCommandExecutor.AUTO_ROOF_PROPERTY))) {
        return true;
      }
    }
    return false;
  }

  // ---- Pictures ----

  /**
   * Returns the file an <code>image</code> or <code>path</code> parameter designates.
   */
  File getFile(AssistantCommand command, String parameter) throws IOException {
    String path = command.getString(parameter);
    if (path == null) {
      path = command.getString("path");
    }
    if (path == null || path.trim().length() == 0) {
      throw new IOException("the \"" + parameter + "\" parameter is required");
    }
    if (ATTACHED_IMAGE.equalsIgnoreCase(path.trim())) {
      File attachedImage = this.executor.getAttachedImage();
      if (attachedImage == null) {
        throw new IOException("no picture is attached to the conversation");
      }
      return attachedImage;
    }
    path = path.trim();
    if (path.startsWith("~" + File.separator) || path.startsWith("~/")) {
      path = System.getProperty("user.home") + path.substring(1);
    }
    File file = new File(path);
    if (!file.isAbsolute()) {
      throw new IOException("the path of the file must be absolute");
    } else if (!file.isFile()) {
      throw new IOException("there is no file " + file);
    }
    return file;
  }

  /**
   * Adds a piece of furniture showing a picture: a panel standing or hung on
   * a wall (painting, poster, photo, screen, mirror), a box with the picture
   * on its front, or a flat object with the picture on its top (rug, carpet).
   */
  private void addPicture(AssistantCommand command, int [] tally, List<String> notes) throws IOException {
    File file = getFile(command, "image");
    byte [] image = AssistantGeneratedModel.readFile(file, MAX_IMAGE_LENGTH);
    int [] imageSize = AssistantGeneratedModel.getImageSize(image);
    if (imageSize == null || imageSize [0] <= 0 || imageSize [1] <= 0) {
      throw new IOException(file.getName() + " isn't a PNG, JPEG or GIF image");
    }
    String mode = command.getString("mode") != null
        ? command.getString("mode").trim().toLowerCase(Locale.ENGLISH) : "panel";
    boolean onTop = "floor".equals(mode) || "rug".equals(mode) || "top".equals(mode);
    float ratio = (float)imageSize [1] / imageSize [0];
    double width = command.getDouble("width", Double.NaN);
    double height = command.getDouble("height", Double.NaN);
    double depth = command.getDouble("depth", Double.NaN);
    if (onTop) {
      // The picture lies on the floor: its height in the image is the depth of the piece
      if (!(width > 0) && !(depth > 0)) {
        width = 200;
      }
      if (!(width > 0)) {
        width = depth / ratio;
      }
      if (!(depth > 0)) {
        depth = width * ratio;
      }
      if (!(height > 0)) {
        height = 1;
      }
    } else {
      if (!(width > 0) && !(height > 0)) {
        width = 100;
      }
      if (!(width > 0)) {
        width = height / ratio;
      }
      if (!(height > 0)) {
        height = width * ratio;
      }
      if (!(depth > 0)) {
        depth = "box".equals(mode) ? width : 3;
      }
    }
    double x = command.getDouble("x", Double.NaN);
    double y = command.getDouble("y", Double.NaN);
    double elevation = command.getDouble("elevation", 0);
    if (!AssistantCommandExecutor.sizeSane(width) || !AssistantCommandExecutor.sizeSane(height)
        || !AssistantCommandExecutor.sizeSane(depth) || !AssistantCommandExecutor.coordinateSane(x)
        || !AssistantCommandExecutor.coordinateSane(y) || !AssistantCommandExecutor.sizeSane(elevation)) {
      notes.add("Ignored add_picture with out-of-range values");
      return;
    }
    Integer sideColor = AssistantCommandExecutor.parseColor(command.getString("color"));
    AssistantGeneratedModel model = AssistantGeneratedModel.buildPictureBox(image, (float)width, (float)depth,
        (float)height, onTop, sideColor != null ? sideColor : DEFAULT_BOX_COLOR);
    String name = command.getString("name");
    if (name == null || name.trim().length() == 0) {
      name = file.getName().replaceFirst("\\.[^.]*$", "");
    }
    HomePieceOfFurniture piece = new HomePieceOfFurniture(new CatalogPieceOfFurniture(name.trim(),
        model.getIcon(), model.getModel(), model.getWidth(), model.getDepth(), model.getHeight(), true, false));
    if (!Double.isNaN(x)) {
      piece.setX((float)x);
    }
    if (!Double.isNaN(y)) {
      piece.setY((float)y);
    }
    piece.setAngle((float)Math.toRadians(command.getDouble("angle", 0)));
    piece.setElevation((float)elevation);
    piece.setLevel(this.home.getSelectedLevel());
    this.executor.beginTurnUpdate();
    this.homeController.getFurnitureController().addFurniture(Collections.singletonList(piece));
    tally [0]++;
    notes.add("Added \"" + name.trim() + "\" showing the picture on its " + (onTop ? "top" : "front") + ", "
        + Math.round(width) + " x " + Math.round(depth) + " x " + Math.round(height) + " cm (width x depth x height)");
  }

  // ---- 3D models ----

  /**
   * Adds a piece of furniture from a 3D model file (OBJ, DAE, 3DS, KMZ, or a
   * ZIP file containing one of them).
   */
  private void importFurniture(AssistantCommand command, int [] tally, List<String> notes) throws IOException {
    File file = getFile(command, "path");
    if (file.length() > MAX_MODEL_LENGTH) {
      throw new IOException(file.getName() + " is larger than " + (MAX_MODEL_LENGTH / 1024 / 1024) + " MB");
    }
    AssistantCommandExecutor.ModelSizeProvider sizeProvider = this.executor.getModelSizeProvider();
    if (sizeProvider == null) {
      throw new IOException("3D models can't be read here");
    }
    Content model = createModelContent(file);
    float [] size = sizeProvider.getModelSize(model);
    if (size == null || !(size [0] > 0) || !(size [1] > 0) || !(size [2] > 0)) {
      throw new IOException(file.getName() + " contains no 3D shape");
    }
    // Scale the model to the given dimension, keeping its proportions
    double width = command.getDouble("width", Double.NaN);
    double depth = command.getDouble("depth", Double.NaN);
    double height = command.getDouble("height", Double.NaN);
    float scale;
    String scaleNote = "";
    if (width > 0) {
      scale = (float)width / size [0];
    } else if (height > 0) {
      scale = (float)height / size [2];
    } else if (depth > 0) {
      scale = (float)depth / size [1];
    } else {
      // Models are drawn in centimeters, meters, inches or millimeters: choose
      // the unit that gives the size of a piece of furniture
      float largest = Math.max(size [0], Math.max(size [1], size [2]));
      scale = largest < 10 ? 100 : largest < 30 ? 2.54f : largest > 5000 ? 0.1f : 1;
      scaleNote = scale == 100 ? " (its unit was taken for the meter)"
          : scale == 2.54f ? " (its unit was taken for the inch)"
          : scale == 0.1f ? " (its unit was taken for the millimeter)" : "";
      scaleNote += "; give \"width\" or \"height\" in cm if the size is wrong";
    }
    float pieceWidth = size [0] * scale;
    float pieceDepth = size [1] * scale;
    float pieceHeight = size [2] * scale;
    double x = command.getDouble("x", Double.NaN);
    double y = command.getDouble("y", Double.NaN);
    double elevation = command.getDouble("elevation", 0);
    if (!AssistantCommandExecutor.sizeSane(pieceWidth) || !AssistantCommandExecutor.sizeSane(pieceDepth)
        || !AssistantCommandExecutor.sizeSane(pieceHeight) || !AssistantCommandExecutor.coordinateSane(x)
        || !AssistantCommandExecutor.coordinateSane(y) || !AssistantCommandExecutor.sizeSane(elevation)) {
      notes.add("Ignored import_furniture with out-of-range values");
      return;
    }
    String name = command.getString("name");
    if (name == null || name.trim().length() == 0) {
      name = file.getName().replaceFirst("\\.[^.]*$", "");
    }
    HomePieceOfFurniture piece = new HomePieceOfFurniture(new CatalogPieceOfFurniture(name.trim(),
        AssistantGeneratedModel.createIconContent(DEFAULT_BOX_COLOR), model,
        pieceWidth, pieceDepth, pieceHeight, true, false));
    if (!Double.isNaN(x)) {
      piece.setX((float)x);
    }
    if (!Double.isNaN(y)) {
      piece.setY((float)y);
    }
    piece.setAngle((float)Math.toRadians(command.getDouble("angle", 0)));
    piece.setElevation((float)elevation);
    piece.setLevel(this.home.getSelectedLevel());
    this.executor.beginTurnUpdate();
    this.homeController.getFurnitureController().addFurniture(Collections.singletonList(piece));
    tally [0]++;
    notes.add("Imported \"" + name.trim() + "\" at " + Math.round(pieceWidth) + " x " + Math.round(pieceDepth)
        + " x " + Math.round(pieceHeight) + " cm (width x depth x height)" + scaleNote);
  }

  /**
   * Returns the content of a model file, copied with the files it needs
   * (materials and images) in a temporary archive saved with the home.
   */
  private static Content createModelContent(File file) throws IOException {
    String lowerName = file.getName().toLowerCase(Locale.ENGLISH);
    if (lowerName.endsWith(".zip")) {
      // The model is the first 3D file of the archive
      ZipFile zip = new ZipFile(file);
      String modelEntry = null;
      try {
        for (Enumeration<? extends ZipEntry> entries = zip.entries(); entries.hasMoreElements(); ) {
          ZipEntry entry = entries.nextElement();
          if (!entry.isDirectory() && MODEL_NAME.matcher(entry.getName()).matches()
              && (modelEntry == null || entry.getName().length() < modelEntry.length())) {
            modelEntry = entry.getName();
          }
        }
      } finally {
        zip.close();
      }
      if (modelEntry == null) {
        throw new IOException(file.getName() + " contains no OBJ, DAE, 3DS or KMZ model");
      }
      File copy = OperatingSystem.createTemporaryFile("model", ".zip");
      java.nio.file.Files.copy(file.toPath(), copy.toPath(), java.nio.file.StandardCopyOption.REPLACE_EXISTING);
      return new TemporaryURLContent(new URL("jar:" + copy.toURI().toURL() + "!/"
          + modelEntry.replace(" ", "%20")));
    } else if (!MODEL_NAME.matcher(lowerName).matches()) {
      throw new IOException("only OBJ, DAE, 3DS, KMZ and ZIP files can be imported");
    }
    // The model with the material files and the images it names, which are
    // looked for beside it
    Map<String, byte []> files = new LinkedHashMap<String, byte []>();
    byte [] model = AssistantGeneratedModel.readFile(file, MAX_MODEL_LENGTH);
    files.put(file.getName(), model);
    File folder = file.getParentFile();
    if (lowerName.endsWith(".obj")) {
      for (String library : findNames(model, "(?m)^\\s*mtllib\\s+(.+?)\\s*$")) {
        File libraryFile = getSibling(folder, library);
        if (libraryFile != null) {
          byte [] libraryData = AssistantGeneratedModel.readFile(libraryFile, MAX_IMAGE_LENGTH);
          files.put(library, libraryData);
          for (String image : findNames(libraryData, "(?mi)^\\s*(?:map_\\w+|bump|disp|decal)\\s+(?:-\\S+\\s+\\S+\\s+)*(.+?)\\s*$")) {
            addSibling(files, folder, image);
          }
        }
      }
    } else if (lowerName.endsWith(".dae")) {
      for (String image : findNames(model, "<init_from>\\s*([^<]+?)\\s*</init_from>")) {
        addSibling(files, folder, image.replace("%20", " "));
      }
    }
    File copy = OperatingSystem.createTemporaryFile("model", ".zip");
    AssistantGeneratedModel.writeZip(copy, files);
    return new TemporaryURLContent(new URL("jar:" + copy.toURI().toURL() + "!/"
        + file.getName().replace(" ", "%20")));
  }

  private static List<String> findNames(byte [] text, String regex) throws IOException {
    List<String> names = new java.util.ArrayList<String>();
    Matcher matcher = Pattern.compile(regex).matcher(new String(text, "ISO-8859-1"));
    while (matcher.find() && names.size() < 200) {
      String name = matcher.group(1).trim();
      if (name.length() > 0 && !names.contains(name)) {
        names.add(name);
      }
    }
    return names;
  }

  /**
   * Returns the file <code>name</code> designates if it's in <code>folder</code>
   * or one of its subfolders, and nowhere else.
   */
  private static File getSibling(File folder, String name) throws IOException {
    if (name.startsWith("file:") || name.contains("://")) {
      return null;
    }
    File file = new File(folder, name.replace('\\', '/'));
    String folderPath = folder.getCanonicalPath() + File.separator;
    return file.isFile() && file.getCanonicalPath().startsWith(folderPath) ? file : null;
  }

  private static void addSibling(Map<String, byte []> files, File folder, String name) throws IOException {
    File file = getSibling(folder, name);
    String entry = name.replace('\\', '/');
    if (file != null && !files.containsKey(entry) && file.length() <= MAX_IMAGE_LENGTH) {
      files.put(entry, AssistantGeneratedModel.readFile(file, MAX_IMAGE_LENGTH));
    }
  }

  // ---- Textures ----

  /**
   * Adds an image file to the textures catalog, and applies it to the
   * targeted rooms, walls and furniture if any.
   */
  private void importTexture(AssistantCommand command, int [] tally, List<String> notes) throws IOException {
    File file = getFile(command, "image");
    byte [] image = AssistantGeneratedModel.readFile(file, MAX_IMAGE_LENGTH);
    int [] imageSize = AssistantGeneratedModel.getImageSize(image);
    if (imageSize == null || imageSize [0] <= 0 || imageSize [1] <= 0) {
      throw new IOException(file.getName() + " isn't a PNG, JPEG or GIF image");
    }
    // The size in centimeters of what the image shows
    double width = command.getDouble("width", 100);
    if (!(width > 0) || !AssistantCommandExecutor.sizeSane(width)) {
      width = 100;
    }
    double height = command.getDouble("height", width * imageSize [1] / imageSize [0]);
    if (!(height > 0) || !AssistantCommandExecutor.sizeSane(height)) {
      height = width * imageSize [1] / imageSize [0];
    }
    String name = command.getString("name");
    if (name == null || name.trim().length() == 0) {
      name = file.getName().replaceFirst("\\.[^.]*$", "");
    }
    name = name.trim();
    // A texture imported before under that name is used again
    CatalogTexture existingTexture = null;
    for (TexturesCategory category : this.preferences.getTexturesCatalog().getCategories()) {
      if (IMPORTED_CATEGORY.equals(category.getName())) {
        for (CatalogTexture texture : category.getTextures()) {
          if (name.equalsIgnoreCase(texture.getName())) {
            existingTexture = texture;
          }
        }
      }
    }
    final CatalogTexture catalogTexture;
    if (existingTexture != null) {
      catalogTexture = existingTexture;
      notes.add("The textures catalog already has a texture \"" + name + "\", which was used");
    } else {
      File copy = OperatingSystem.createTemporaryFile("texture", "." + AssistantGeneratedModel.getImageExtension(image));
      java.nio.file.Files.write(copy.toPath(), image);
      catalogTexture = new CatalogTexture(name,
          new TemporaryURLContent(copy.toURI().toURL()), (float)width, (float)height, true);
      this.preferences.getTexturesCatalog().add(new TexturesCategory(IMPORTED_CATEGORY), catalogTexture);
      notes.add("Added the texture \"" + name + "\" to the textures catalog (category " + IMPORTED_CATEGORY + ")");
    }
    final List<Selectable> targets = this.executor.resolveTargets(command);
    if (!targets.isEmpty()) {
      final String part = command.getString("part") != null
          ? command.getString("part").toLowerCase(Locale.ENGLISH) : "";
      final int [] changed = {0};
      this.executor.postModification(targets, new Runnable() {
          public void run() {
            for (Selectable item : targets) {
              HomeTexture texture = new HomeTexture(catalogTexture);
              if (item instanceof Room) {
                if ("ceiling".equals(part)) {
                  ((Room)item).setCeilingTexture(texture);
                } else {
                  ((Room)item).setFloorTexture(texture);
                }
                changed [0]++;
              } else if (item instanceof Wall) {
                if (!"right".equals(part)) {
                  ((Wall)item).setLeftSideTexture(texture);
                }
                if (!"left".equals(part)) {
                  ((Wall)item).setRightSideTexture(texture);
                }
                changed [0]++;
              } else if (item instanceof HomePieceOfFurniture && ((HomePieceOfFurniture)item).isTexturable()) {
                ((HomePieceOfFurniture)item).setTexture(texture);
                changed [0]++;
              }
            }
          }
        });
      tally [4] += changed [0];
    }
  }
}
