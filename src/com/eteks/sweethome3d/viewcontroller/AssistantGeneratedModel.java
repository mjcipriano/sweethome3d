package com.eteks.sweethome3d.viewcontroller;

import java.io.ByteArrayOutputStream;
import java.io.File;
import java.io.FileInputStream;
import java.io.FileOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.net.URL;
import java.util.LinkedHashMap;
import java.util.Locale;
import java.util.Map;
import java.util.zip.CRC32;
import java.util.zip.Deflater;
import java.util.zip.ZipEntry;
import java.util.zip.ZipOutputStream;

import com.eteks.sweethome3d.model.Content;
import com.eteks.sweethome3d.tools.OperatingSystem;
import com.eteks.sweethome3d.tools.TemporaryURLContent;

/**
 * A 3D model generated by the design assistant (stairs, a box showing a
 * picture...), with its icon. The model is an OBJ file stored with its
 * material file and its images in a temporary archive saved with the home.
 * @author Sweet Home 3D
 */
public class AssistantGeneratedModel {
  private final Content model;
  private final Content icon;
  private final float   width;
  private final float   depth;
  private final float   height;

  private AssistantGeneratedModel(Content model, Content icon, float width, float depth, float height) {
    this.model = model;
    this.icon = icon;
    this.width = width;
    this.depth = depth;
    this.height = height;
  }

  public Content getModel() {
    return this.model;
  }

  public Content getIcon() {
    return this.icon;
  }

  public float getWidth() {
    return this.width;
  }

  public float getDepth() {
    return this.depth;
  }

  public float getHeight() {
    return this.height;
  }

  /**
   * Returns the count of steps of stairs climbing <code>rise</code> centimeters
   * with comfortable risers of about 17.5 cm.
   */
  public static int getStepCount(float rise) {
    return Math.max(2, Math.round(rise / 17.5f));
  }

  /**
   * Builds a straight flight of stairs. Its bottom step is at the front of
   * the piece and its top at the back, as someone facing the piece climbs it.
   * @param width  width of the steps in centimeters
   * @param length length of the flight in centimeters
   * @param rise   height climbed in centimeters
   */
  public static AssistantGeneratedModel buildStairs(float width, float length, float rise,
                                                    int color) throws IOException {
    int stepCount = getStepCount(rise);
    float stepDepth = length / stepCount;
    float stepHeight = rise / stepCount;
    // Materials get a name of their own, as renderers tell them apart by their name
    String material = "stairs_" + Long.toHexString(System.nanoTime());
    StringBuilder obj = new StringBuilder("# Stairs generated by Sweet Home 3D\nmtllib " + material
        + ".mtl\ng stairs\nusemtl " + material + "\n");
    int vertexCount = 0;
    for (int i = 0; i < stepCount; i++) {
      // Each step is a block from the floor up to its tread
      float front = length / 2 - i * stepDepth;
      vertexCount = appendBox(obj, vertexCount, -width / 2, 0, front - stepDepth,
          width / 2, (i + 1) * stepHeight, front, false);
    }
    String mtl = material(material, color, null);
    // Files named after the model too: models saved in a home are told apart by their file names
    Map<String, byte []> files = new LinkedHashMap<String, byte []>();
    files.put(material + ".obj", obj.toString().getBytes("ISO-8859-1"));
    files.put(material + ".mtl", mtl.getBytes("ISO-8859-1"));
    files.put("icon_" + material + ".png", createIcon(color, true));
    return store("stairs", files, width, length, rise);
  }

  /**
   * Builds a box showing a picture: on its front for a standing panel
   * (a painting, a poster, a screen) or a box, on its top for a flat object (a rug).
   * @param image    the bytes of a PNG, JPEG or GIF image
   * @param onTop    <code>true</code> to show the picture on the top of the box
   */
  public static AssistantGeneratedModel buildPictureBox(byte [] image, float width, float depth,
                                                        float height, boolean onTop,
                                                        int sideColor) throws IOException {
    String extension = getImageExtension(image);
    if (extension == null) {
      throw new IOException("Not a PNG, JPEG or GIF image");
    }
    float w = width / 2;
    float d = depth / 2;
    String suffix = Long.toHexString(System.nanoTime());
    StringBuilder obj = new StringBuilder("# Picture generated by Sweet Home 3D\nmtllib picture_" + suffix
        + ".mtl\ng box\nusemtl box_" + suffix + "\n");
    appendBox(obj, 0, -w, 0, -d, w, height, d, true);
    // The textured face is drawn again over the box, a hair in front of it
    obj.append("vt 0 0\nvt 1 0\nvt 1 1\nvt 0 1\ng picture\nusemtl picture_" + suffix + "\n");
    float gap = 0.05f;
    if (onTop) {
      obj.append(vertex(-w, height + gap, d)).append(vertex(w, height + gap, d))
         .append(vertex(w, height + gap, -d)).append(vertex(-w, height + gap, -d));
    } else {
      obj.append(vertex(-w, 0, d + gap)).append(vertex(w, 0, d + gap))
         .append(vertex(w, height, d + gap)).append(vertex(-w, height, d + gap));
    }
    obj.append("f 9/1 10/2 11/3 12/4\n");
    String mtl = material("box_" + suffix, sideColor, null)
        + material("picture_" + suffix, 0xFFFFFF, "picture_" + suffix + "." + extension);
    Map<String, byte []> files = new LinkedHashMap<String, byte []>();
    files.put("picture_" + suffix + ".obj", obj.toString().getBytes("ISO-8859-1"));
    files.put("picture_" + suffix + ".mtl", mtl.getBytes("ISO-8859-1"));
    files.put("picture_" + suffix + "." + extension, image);
    // The picture is also the icon shown in the plan and the furniture list
    files.put("icon_" + suffix + "." + extension, image);
    return store("picture", files, width, depth + (onTop ? 0 : gap), height + (onTop ? gap : 0));
  }

  /**
   * Returns a generic icon for a model that has none.
   */
  public static Content createIconContent(int color) throws IOException {
    return storeFile("icon", ".png", createIcon(color, false));
  }

  /**
   * Stores the files of a model in a temporary archive, and its icon (the file
   * whose name starts with <code>icon_</code>) in a file of its own: a home
   * saves the contents of an archive as a whole, under the name of only one of them.
   */
  private static AssistantGeneratedModel store(String prefix, Map<String, byte []> files,
                                               float width, float depth, float height) throws IOException {
    Map<String, byte []> modelFiles = new LinkedHashMap<String, byte []>();
    String modelName = null;
    Content icon = null;
    for (Map.Entry<String, byte []> entry : files.entrySet()) {
      String name = entry.getKey();
      if (name.startsWith("icon_")) {
        icon = storeFile("icon", name.substring(name.lastIndexOf('.')), entry.getValue());
      } else {
        modelFiles.put(name, entry.getValue());
        if (name.endsWith(".obj")) {
          modelName = name;
        }
      }
    }
    File file = OperatingSystem.createTemporaryFile(prefix, ".zip");
    writeZip(file, modelFiles);
    return new AssistantGeneratedModel(
        new TemporaryURLContent(new URL("jar:" + file.toURI().toURL() + "!/" + modelName)),
        icon, width, depth, height);
  }

  /**
   * Returns the content of a temporary file containing <code>data</code>.
   */
  static Content storeFile(String prefix, String extension, byte [] data) throws IOException {
    File file = OperatingSystem.createTemporaryFile(prefix, extension);
    FileOutputStream out = new FileOutputStream(file);
    try {
      out.write(data);
    } finally {
      out.close();
    }
    return new TemporaryURLContent(file.toURI().toURL());
  }

  static void writeZip(File file, Map<String, byte []> files) throws IOException {
    ZipOutputStream zip = new ZipOutputStream(new FileOutputStream(file));
    try {
      for (Map.Entry<String, byte []> entry : files.entrySet()) {
        zip.putNextEntry(new ZipEntry(entry.getKey()));
        zip.write(entry.getValue());
        zip.closeEntry();
      }
    } finally {
      zip.close();
    }
  }

  private static String vertex(float x, float y, float z) {
    return String.format(Locale.US, "v %.3f %.3f %.3f\n", x, y, z);
  }

  /**
   * Appends a box to <code>obj</code> and returns the new count of vertices.
   */
  private static int appendBox(StringBuilder obj, int vertexCount, float x1, float y1, float z1,
                               float x2, float y2, float z2, boolean unused) {
    obj.append(vertex(x1, y1, z1)).append(vertex(x2, y1, z1)).append(vertex(x2, y1, z2)).append(vertex(x1, y1, z2))
       .append(vertex(x1, y2, z1)).append(vertex(x2, y2, z1)).append(vertex(x2, y2, z2)).append(vertex(x1, y2, z2));
    // Faces turned outward: top, bottom, front (z2), back (z1), left (x1), right (x2)
    int [][] faces = {{8, 7, 6, 5}, {1, 2, 3, 4}, {4, 3, 7, 8}, {2, 1, 5, 6}, {1, 4, 8, 5}, {3, 2, 6, 7}};
    for (int [] face : faces) {
      obj.append('f');
      for (int index : face) {
        obj.append(' ').append(vertexCount + index);
      }
      obj.append('\n');
    }
    return vertexCount + 8;
  }

  private static String material(String name, int color, String image) {
    return String.format(Locale.US, "newmtl %s\nKa 0.2 0.2 0.2\nKd %.4f %.4f %.4f\nKs 0 0 0\nd 1\nillum 1\n",
        name, ((color >> 16) & 0xFF) / 255f, ((color >> 8) & 0xFF) / 255f, (color & 0xFF) / 255f)
        + (image != null ? "map_Kd " + image + "\n" : "");
  }

  /**
   * Returns <code>png</code>, <code>jpg</code> or <code>gif</code> according
   * to the first bytes of <code>image</code>, or <code>null</code> if it's none of them.
   */
  public static String getImageExtension(byte [] image) {
    if (image.length > 8 && (image [0] & 0xFF) == 0x89 && image [1] == 'P' && image [2] == 'N' && image [3] == 'G') {
      return "png";
    } else if (image.length > 3 && (image [0] & 0xFF) == 0xFF && (image [1] & 0xFF) == 0xD8) {
      return "jpg";
    } else if (image.length > 6 && image [0] == 'G' && image [1] == 'I' && image [2] == 'F') {
      return "gif";
    }
    return null;
  }

  /**
   * Returns the width and height in pixels of a PNG, JPEG or GIF image, read
   * from its header, or <code>null</code> if they can't be found.
   */
  public static int [] getImageSize(byte [] image) {
    String extension = getImageExtension(image);
    if ("png".equals(extension) && image.length >= 24) {
      return new int [] {readInt(image, 16), readInt(image, 20)};
    } else if ("gif".equals(extension) && image.length >= 10) {
      return new int [] {(image [6] & 0xFF) | (image [7] & 0xFF) << 8, (image [8] & 0xFF) | (image [9] & 0xFF) << 8};
    } else if ("jpg".equals(extension)) {
      // Walk the segments up to the start of frame, which holds the size
      int offset = 2;
      while (offset + 9 < image.length) {
        if ((image [offset] & 0xFF) != 0xFF) {
          return null;
        }
        int marker = image [offset + 1] & 0xFF;
        int length = (image [offset + 2] & 0xFF) << 8 | (image [offset + 3] & 0xFF);
        if (marker >= 0xC0 && marker <= 0xCF && marker != 0xC4 && marker != 0xC8 && marker != 0xCC) {
          return new int [] {(image [offset + 7] & 0xFF) << 8 | (image [offset + 8] & 0xFF),
                             (image [offset + 5] & 0xFF) << 8 | (image [offset + 6] & 0xFF)};
        }
        offset += 2 + length;
      }
    }
    return null;
  }

  private static int readInt(byte [] data, int offset) {
    return (data [offset] & 0xFF) << 24 | (data [offset + 1] & 0xFF) << 16
        | (data [offset + 2] & 0xFF) << 8 | (data [offset + 3] & 0xFF);
  }

  /**
   * Reads a file of <code>maxLength</code> bytes at most.
   */
  public static byte [] readFile(File file, long maxLength) throws IOException {
    if (!file.isFile()) {
      throw new IOException("No file " + file);
    } else if (file.length() > maxLength) {
      throw new IOException(file.getName() + " is larger than " + (maxLength / 1024 / 1024) + " MB");
    }
    InputStream in = new FileInputStream(file);
    try {
      ByteArrayOutputStream out = new ByteArrayOutputStream((int)file.length());
      byte [] buffer = new byte [8192];
      int count;
      while ((count = in.read(buffer)) > 0) {
        out.write(buffer, 0, count);
      }
      return out.toByteArray();
    } finally {
      in.close();
    }
  }

  /**
   * Returns a PNG icon drawn without the AWT toolkit this package doesn't
   * use: steps or a plain square of the given color.
   */
  private static byte [] createIcon(int color, boolean steps) throws IOException {
    int size = 48;
    byte [] pixels = new byte [size * (1 + size * 4)];
    for (int y = 0; y < size; y++) {
      int row = y * (1 + size * 4);
      for (int x = 0; x < size; x++) {
        boolean drawn;
        float shade = 1;
        if (steps) {
          // Six steps climbing to the right
          int step = Math.min(5, (x - 4) / 7);
          drawn = x >= 4 && x < 46 && y >= 40 - (step + 1) * 6 && y < 42;
          shade = (x - 4) % 7 == 0 || y == 40 - (step + 1) * 6 ? 0.6f : 1;
        } else {
          drawn = x >= 6 && x < 42 && y >= 6 && y < 42;
          shade = x == 6 || x == 41 || y == 6 || y == 41 ? 0.6f : 1;
        }
        if (drawn) {
          int pixel = row + 1 + x * 4;
          pixels [pixel] = (byte)(((color >> 16) & 0xFF) * shade);
          pixels [pixel + 1] = (byte)(((color >> 8) & 0xFF) * shade);
          pixels [pixel + 2] = (byte)((color & 0xFF) * shade);
          pixels [pixel + 3] = (byte)0xFF;
        }
      }
    }
    Deflater deflater = new Deflater();
    deflater.setInput(pixels);
    deflater.finish();
    ByteArrayOutputStream compressed = new ByteArrayOutputStream();
    byte [] buffer = new byte [4096];
    while (!deflater.finished()) {
      compressed.write(buffer, 0, deflater.deflate(buffer));
    }
    deflater.end();
    ByteArrayOutputStream png = new ByteArrayOutputStream();
    png.write(new byte [] {(byte)0x89, 'P', 'N', 'G', '\r', '\n', 0x1A, '\n'});
    writeChunk(png, "IHDR", new byte [] {0, 0, 0, (byte)size, 0, 0, 0, (byte)size, 8, 6, 0, 0, 0});
    writeChunk(png, "IDAT", compressed.toByteArray());
    writeChunk(png, "IEND", new byte [0]);
    return png.toByteArray();
  }

  private static void writeChunk(ByteArrayOutputStream out, String type, byte [] data) throws IOException {
    byte [] typeBytes = type.getBytes("ISO-8859-1");
    writeInt(out, data.length);
    out.write(typeBytes);
    out.write(data);
    CRC32 crc = new CRC32();
    crc.update(typeBytes);
    crc.update(data);
    writeInt(out, (int)crc.getValue());
  }

  private static void writeInt(ByteArrayOutputStream out, int value) {
    out.write(value >>> 24);
    out.write(value >>> 16);
    out.write(value >>> 8);
    out.write(value);
  }
}
